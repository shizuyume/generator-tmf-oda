import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { buildFEIR } from './buildFEIR.mjs';
import { loadAdapter } from '../../libs/adapter.mjs';
import * as mcsCommonAdapter from '../../libs/mcs-common.adapter.js';
import { allocateFePort, scanFePorts } from './allocateFePort.mjs';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const templateRoot = path.resolve(here, '..', '..', 'templates');

/** Direktori template per library (ui.library dari FE spec; resmi mui|neudela|fe-default).
 * "fe-default" sudah membawa prefix "fe-" sendiri - jangan digandakan jadi "fe-fe-default". */
export function feTemplateDirFor(library = 'mui') {
  const dirName = library.startsWith('fe-') ? library : `fe-${library}`;
  const dir = path.join(templateRoot, dirName);
  if (!fs.existsSync(dir)) {
    throw new Error(`scaffoldApp: template "${dir}" tidak ada (ui.library="${library}" tak terdaftar)`);
  }
  return dir;
}
export const feTemplateDir = feTemplateDirFor('mui');

/** Lokasi repo lib neudela (workspace root) — dipakai token NEUDELA_REF utk deps file:. */
export function neudelaLibDir() {
  return path.resolve(here, '..', '..', '..', 'neudela');
}

const GENERATED_BANNER = '// GENERATED by fe-gen scaffold - DO NOT EDIT. Re-run the scaffold instead.';

/* ── template walk + render (pola newService: token {{TOKEN}}, THROW pada placeholder hilang) ── */

function walk(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(abs, base));
    else out.push(path.relative(base, abs).split(path.sep).join('/'));
  }
  return out;
}

export function renderFeTemplate(text, tokens) {
  return text.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in tokens)) throw new Error(`template placeholder ${m} has no value`);
    return tokens[key];
  });
}

/* ── FEIR resolve: prioritas .feir/ cache, fallback buildFEIR (pola cmd fe-spec/fe-ir) ── */

export function feirCachePath(specPath, feirRoot) {
  const base = path.basename(specPath, path.extname(specPath));
  return path.join(feirRoot, `${base}.feir.json`);
}

export async function resolveFEIR(specPath, { feirRoots = [], writeCache = true } = {}) {
  const roots = feirRoots.filter(Boolean);
  for (const root of roots) {
    const p = feirCachePath(specPath, root);
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8'));
  }
  const { ir } = await buildFEIR(specPath);
  if (writeCache && roots.length) {
    fs.mkdirSync(roots[0], { recursive: true });
    fs.writeFileSync(feirCachePath(specPath, roots[0]), JSON.stringify(ir, null, 2) + '\n', 'utf8');
  }
  return ir;
}

/* ── labels dict dari YAML (i18n single-lang v1; languageSwitch OFF) ── */

export function labelsFromFEIR(ir) {
  const dict = {
    lang: ir.meta?.lang ?? 'id',
    appTitle: ir.meta?.label ?? ir.meta?.name ?? 'Aplikasi',
    appName: ir.meta?.name ?? '',
    description: ir.meta?.description ?? '',
  };
  for (const p of ir.pages ?? []) {
    if (p.title) dict[`page.${p.id}`] = p.title;
  }
  return dict;
}

/* ── main scaffold ─────────────────────────────────────────────────── */

/**
 * Scaffold CRA5+Craco MUI full-repo app dari FE IR ke feTargetRoot/<meta.name>.
 * - Menolak bila dir target ada & non-empty (exit 5 pola BE, err.code 'E_EXISTS').
 * - Port FE dialokasikan dari fePortRange (scan `set PORT=` di target root).
 * - theme.generated.ts ditulis dari generator/libs/mui.adapter.js theme() (scaffold-time,
 *   deterministik) — template app tidak meng-import generator.
 */
export function scaffoldApp(ir, { feTargetRoot, port = null, bePort = 3736, fePortRange = [5012, 5099] }) {
  const appName = (ir.meta?.name || 'fe-app').trim().replace(/\s+/g, '-');
  const appDir = path.join(feTargetRoot, appName);
  const library = ir.ui?.library ?? 'mui';
  // federationTemplate is a SEPARATE axis from ui.library (which stays 'mui' - visual
  // library unchanged, only import source/output shape differs). Selects the fe-mcs-common
  // template dir + adapter INSTEAD of feTemplateDirFor(library)/loadAdapter(library) below.
  const federationTemplate = ir.output?.mfe?.federationTemplate ?? 'none';
  const isMcsCommon = federationTemplate === 'common-remote';
  const adapter = isMcsCommon ? mcsCommonAdapter : loadAdapter(library);

  if (fs.existsSync(appDir) && fs.readdirSync(appDir).length) {
    const err = new Error(`refusing to scaffold: ${appDir} already exists and is non-empty`);
    err.code = 'E_EXISTS';
    throw err;
  }
  if (!fs.existsSync(feTargetRoot)) fs.mkdirSync(feTargetRoot, { recursive: true });

  // Port resolution order: argumen eksplisit (mis. --port CLI) > port dari YAML
  // (output.fullRepo.port / output.mfe.port) > auto-allocate (scan fePortRange).
  // Port dari YAML tetap lewat scanFePorts agar tabrakan dgn app lain terdeteksi.
  const specPort = ir.output?.fullRepo?.port ?? ir.output?.mfe?.port ?? null;
  const resolvedPort = port ?? specPort;
  const alloc = resolvedPort != null
    ? { port: resolvedPort, used: scanFePorts(feTargetRoot) }
    : allocateFePort(feTargetRoot, fePortRange);
  const tokens = {
    APP_NAME: appName,
    PORT: String(alloc.port),
    BE_PORT: String(bePort),
  };
  if (library === 'neudela') {
    const rel = path.relative(appDir, neudelaLibDir()).split(path.sep).join('/');
    tokens.NEUDELA_REF = `file:${rel}`;
  }

  const written = [];
  const writeFile = (rel, content) => {
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  // 1. salin template per library, isi token (render THROW pada placeholder hilang)
  const tplDir = isMcsCommon ? feTemplateDirFor('mcs-common') : feTemplateDirFor(library);
  for (const rel of walk(tplDir)) {
    const text = fs.readFileSync(path.join(tplDir, rel), 'utf8');
    const rendered = renderFeTemplate(text, tokens);
    writeFile(rel === 'package.json.template' ? 'package.json' : rel, rendered);
  }

  // 2. file data di-generate (deterministik dari YAML): theme + i18n labels
  // SKIP total utk mcs-common: tidak ada ThemeProvider/i18n layer sendiri - common_remote
  // membawa styling-nya sendiri dan product-qualification tidak punya lapisan i18n
  // (verified) - src/gen/ tidak dipakai template ini sama sekali.
  if (!isMcsCommon) {
  const tokensData = ir.theme?.tokens ?? {};
  const lightTheme = adapter.theme(tokensData, false);
  const darkThemeObj = adapter.theme(tokensData, true);
  writeFile(
    'src/gen/i18n.generated.ts',
    `${GENERATED_BANNER}

export const labels: Record<string, string> = ${JSON.stringify(labelsFromFEIR(ir), null, 2)};
`,
  );
  if (library === 'neudela' || library === 'fe-default') {
    // neudela & fe-default: tema = CSS variables (pola tokens.css) — objek :root / .dark-theme;
    // runtime theme.ts menyuntikkan <style> (fe-default) atau ditulis langsung ke tokens.css (lihat item 2 plan).
    writeFile(
      'src/gen/theme.generated.ts',
      `${GENERATED_BANNER}
// Tema CSS variables dari FE spec ui.theme.tokens via generator/libs/<lib>.adapter.js theme()
// (dipanggil scaffold-time — deterministik). buildTheme() di src/gen/theme.ts menyuntikkan <style>.
export const genThemeLight: Record<string, Record<string, string>> = ${JSON.stringify(lightTheme, null, 2)};

export const genThemeDark: Record<string, Record<string, string>> = ${JSON.stringify(darkThemeObj, null, 2)};
`,
    );
  } else {
    const darkTheme = darkThemeObj.colorSchemes?.dark ?? null;
    writeFile(
      'src/gen/theme.generated.ts',
      `${GENERATED_BANNER}
import type { ThemeOptions } from '@mui/material/styles';

// Data tema dari FE spec ui.theme.tokens via generator/libs/<lib>.adapter.js theme()
// (dipanggil scaffold-time — deterministik). createTheme di-instansiasi di src/gen/theme.ts.
export const genThemeLight: ThemeOptions = ${JSON.stringify(lightTheme, null, 2)};

export const genThemeDark: ThemeOptions = ${JSON.stringify(darkTheme, null, 2)};
`,
    );
  }
  } // !isMcsCommon

  return { appName, appDir, port: alloc.port, used: alloc.used ?? [], written: written.sort(), bePort, library, federationTemplate };
}

export async function scaffoldFromSpec(specPath, opts = {}) {
  const feTargetRoot = path.resolve(opts.feTargetRoot);
  const feir = await resolveFEIR(path.resolve(specPath), {
    feirRoots: opts.feirRoots,
    writeCache: opts.writeCache !== false,
  });
  return { feir, ...scaffoldApp(feir, { feTargetRoot, port: opts.port ?? null, bePort: opts.bePort ?? 3736, fePortRange: opts.fePortRange ?? [5012, 5099] }) };
}