// emitFESpec.mjs — M1 frontend-spec baseline emitter (IR -> frontend-spec-*.yaml)
// API: emitFESpec(ir) -> Promise<string> (validated YAML text; throws when output
// fails the todo-1 validator so an invalid file is never written).
// Cross-checked by todo 3 (determinism golden) — keep the emitter a pure function
// of the IR: no clock, no random, no cwd-dependent content.
import { kebab, words } from '../ir/naming.mjs';
import { validateString } from './validateFESpec.mjs';

const IND = '  ';
const pad = (n, s) => IND.repeat(n) + s;

/** Quote a scalar only when YAML would misread it; keep the output human-clean. */
const q = v => {
  const s = String(v ?? '');
  return /^[A-Za-z0-9][A-Za-z0-9 _\-./()@%'+]*$/.test(s) ? s : JSON.stringify(s);
};

const humanize = s =>
  words(s).map(w => (w ? w[0].toUpperCase() + w.slice(1) : w)).join(' ');

const plural = s => (/(s|x|ch|sh|z)$/i.test(s) ? `${s}es` : `${s}s`);

const OP_METHOD = { list: 'GET', create: 'POST', retrieve: 'GET', update: 'PATCH', delete: 'DELETE' };
const INFRA_PROP = new Set(['@baseType', '@schemaLocation', 'id', 'href']);

const fieldLabel = name =>
  name === 'name' ? 'Nama' : name === 'description' ? 'Deskripsi' : name === 'id' ? 'ID' : humanize(name);

function inputType(f) {
  if (f.name === 'description') return 'textarea';
  if (f.tsType === 'boolean' || f.column?.type === 'boolean') return 'toggle';
  if (f.enumValues?.length) return 'select';
  return 'text';
}

function scalarWire(f) {
  return f.sourceProp || f.name;
}

function pageIcon(name) {
  if (/Validation/i.test(name)) return 'FileCheck';
  if (/Address/i.test(name)) return 'MapPin';
  if (/Algorithm|Policy|Charge/i.test(name)) return 'Percent';
  return 'LayoutDashboard';
}

const subOf = (r, prop) => r.subResources.find(s => s.propertyName === prop) ?? null;
const refOf = (r, prop) => r.resourceRefs.find(f => f.name === prop) ?? null;
const scalarOf = (r, prop) => r.fields.find(f => f.name === prop) ?? null;

/** Resource-level flattenedRef (cross-component ref) usable as payload object: needs id/href/name column. */
function flatOf(r, prop) {
  const fr = r.flattenedRefs?.find(f => f.name === prop) ?? null;
  return fr && fr.columns.some(c => ['id', 'href', 'name'].includes(c.sourceProp)) ? fr : null;
}

/** Bagaimana sebuah prop shape di-render di payload form: null = tak bisa dirender (bukan field user). */
function payloadEntryKind(r, p) {
  if (p === '@type') return 'atType';
  if (subOf(r, p)) return 'sub';
  if (refOf(r, p)) return 'ref';
  if (flatOf(r, p)) return 'flat';
  if (scalarOf(r, p)) return 'scalar';
  return null;
}

function renderValueBase(basePath, path) {
  return `"{{api.basePath}}${path}"`;
}

