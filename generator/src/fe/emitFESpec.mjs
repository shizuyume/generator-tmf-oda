function header(lines, ir) {
  const m = ir.meta;
  lines.push('# ============================================================');
  lines.push(`# TMF${m.tmfNumber} frontend-spec baseline — generated by tmfgen fe-spec`);
  lines.push('# ------------------------------------------------------------');
  lines.push('# Sumber IR : generator/ir-cache (hasil `tmfgen ir`)');
  lines.push(`# Base path : /${m.basePath}`);
  lines.push('# GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.');
  lines.push('# ============================================================');
  lines.push('');
}

function metaBlock(lines, ir) {
  const m = ir.meta;
  const portal = m.serviceNameSuggestion.replace(/-service$/, '') + '-portal';
  const name = /^[a-z0-9-]+$/.test(portal) ? portal : kebab(ir.resources[0]?.name ?? 'app') + '-portal';
  lines.push('meta:');
  lines.push(pad(1, `name: ${q(name)}`));
  lines.push(pad(1, `label: ${q(m.specTitle)}`));
  lines.push(pad(1, 'version: 0.1.0'));
  lines.push(pad(1, 'lang: id'));
  lines.push(pad(1, `description: ${q(`Portal manajemen ${m.specTitle} (TMF${m.tmfNumber})`)}`));
  lines.push('');
}

function apiBlock(lines, ir) {
  const m = ir.meta;
  lines.push('api:');
  lines.push(pad(1, `basePath: ${q(`/${m.basePath}`)}`));
  lines.push(pad(1, 'headers:                              # BE generated pakai ApiKeyGuard'));
  lines.push(pad(2, '# KONTRAK RUNTIME: nilai secret HANYA lewat {{config.*}} (runtime gen.config),'));
  lines.push(pad(2, '# TIDAK pernah lewat build-env / {{env.*}}.'));
  lines.push(pad(2, `x-api-key: ${q('{{config.TMF_API_KEY}}')}`));
  lines.push(pad(1, 'endpoints:'));
  for (const r of ir.resources) {
    for (const op of ['list', 'create', 'retrieve', 'update', 'delete']) {
      if (!r.operations[op]) continue;
      const path = op === 'list' || op === 'create' ? r.paths.collection : r.paths.item;
      lines.push(pad(2, `${q(`${r.camelName}.${op}`)}: ${OP_METHOD[op].padEnd(5)} ${path}`));
    }
  }
  if (ir.hub.present || ir.listeners.length) {
    lines.push(pad(2, '# hub/listener (event subscription) — bukan resource CRUD;'));
    lines.push(pad(2, '#   POST /hub, DELETE /hub/{id}; listener POST ' + ir.listeners.map(l => l.path).join(', ')));
  }
  lines.push('');
}

