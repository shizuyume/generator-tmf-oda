// emit/mcs-common/exposes.mjs — src/exposes/<X>.tsx wrapper per output.mfe.exposes[]
// entry (createProtectedPage(() => import(pagePath)) - lazy+Suspense+ErrorBoundary,
// matching product-qualification's src/exposes/*.tsx exactly).
import fs from 'node:fs';
import path from 'node:path';
import { buildResourceModel, listPages } from './resourceModel.mjs';

const BANNER = '// GENERATED by fe-gen emit mcs-common - DO NOT EDIT. Re-run `fe-gen emit` instead.';

function exposeFile(pageName, pagePath) {
  return `${BANNER}
import { createProtectedPage } from '../federation/createProtectedPage';

export default createProtectedPage(() => import('${pagePath}'), {
  pageName: ${JSON.stringify(pageName)},
});
`;
}

export function emitExposes(feir, appDir) {
  const exposes = feir.output?.mfe?.exposes ?? [];
  const models = listPages(feir).map((p) => buildResourceModel(p));
  const hub = feir.output?.mfe?.hub === true;

  const written = [];
  for (const e of exposes) {
    const rel = e.target.startsWith('src/') ? e.target : `src/${e.target}`;
    const base = path.basename(rel, path.extname(rel));
    let pagePath;
    let pageName = base;
    if (hub && /^hub$/i.test(base)) {
      pagePath = '../pages/hub';
      pageName = 'Hub';
    } else {
      const model = models.find((m) => m.ResourceName === base);
      if (!model) {
        throw new Error(`emit/mcs-common/exposes: expose "${e.key}" (target ${e.target}) matches no resource ("${base}" != any of ${models.map((m) => m.ResourceName).join(', ')}) and is not "Hub"`);
      }
      pagePath = `../pages/${model.resourceKebab}`;
      pageName = model.ResourceName;
    }
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, exposeFile(pageName, pagePath), 'utf8');
    written.push(rel);
  }
  return { written, summary: `exposes: ${exposes.length} wrapper(s)` };
}
