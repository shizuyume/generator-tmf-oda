// emit/mcs-common/craco.mjs — craco.config.js with REAL Module Federation `remotes`
// (built from output.mfe.remotes[]) - the whole point of this template vs. emit/mfe.mjs's
// permanently-empty remotes:{}. Naming convention (remoteName/entryFile) mirrors mfe.mjs.
import fs from 'node:fs';
import path from 'node:path';

const BANNER = '// GENERATED by fe-gen emit mcs-common - DO NOT EDIT. Re-run `fe-gen emit` instead.';

const snake = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[-\s]+/g, '_').toLowerCase();
const camel = (s) => String(s).replace(/[-_]+([a-zA-Z])/g, (_, c) => c.toUpperCase());
const q1 = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function cracoFile(feir) {
  const mfe = feir.output?.mfe ?? {};
  const moduleName = mfe.moduleName || 'mfe';
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(String(moduleName))) {
    throw new Error(`emit/mcs-common/craco: output.mfe.moduleName "${moduleName}" bukan camelCase valid`);
  }
  const remoteName = `${snake(moduleName)}_remote`;
  const entryFile = `${camel(moduleName)}RemoteEntry.js`;
  const exposes = mfe.exposes ?? [];
  if (!exposes.length) {
    throw new Error('emit/mcs-common/craco: output.mfe.exposes kosong - MFE tanpa exposes tidak bermakna');
  }
  const remotes = mfe.remotes ?? [];
  if (!remotes.length) {
    throw new Error('emit/mcs-common/craco: output.mfe.remotes kosong - federationTemplate=common-remote wajib punya minimal 1 remote (mis. common_remote)');
  }

  const exposesLiteral = exposes
    .map((e) => `  ${q1(e.key)}: ${q1(`./${String(e.target).replace(/^\.\//, '')}`)},`)
    .join('\n');
  const remotesLiteral = remotes
    .map((r) => `  ${q1(r.name)}: \`${r.name}@\${process.env.${r.urlEnvVar} || ${q1(r.defaultUrl)}}/${r.entryFile}\`,`)
    .join('\n');

  const L = [];
  L.push(BANNER);
  L.push('// Module Federation (mcs-common) — CONSUMES real remotes (see output.mfe.remotes),');
  L.push('// unlike emit/mfe.mjs which always leaves remotes:{} (self-contained adapters).');
  L.push(`//   name      = snake_case(moduleName) + '_remote'  (${remoteName})`);
  L.push(`//   filename  = camelCase(moduleName) + 'RemoteEntry.js'  (${entryFile})`);
  L.push('const { ModuleFederationPlugin } = require("webpack").container;');
  L.push('');
  L.push('module.exports = {');
  L.push('  webpack: {');
  L.push('    configure: (webpackConfig) => {');
  L.push('      webpackConfig.output.publicPath = "auto";');
  L.push('      webpackConfig.output.crossOriginLoading = "anonymous";');
  L.push('      webpackConfig.plugins.push(');
  L.push('        new ModuleFederationPlugin({');
  L.push(`          name: ${q1(remoteName)},`);
  L.push(`          filename: ${q1(entryFile)},`);
  L.push('          remotes: {');
  L.push(remotesLiteral);
  L.push('          },');
  L.push('          exposes: {');
  L.push(exposesLiteral);
  L.push('          },');
  L.push('          shared: {');
  L.push('            react: { singleton: true, requiredVersion: false },');
  L.push('            "react-dom": { singleton: true, requiredVersion: false },');
  L.push('            "react-router-dom": { singleton: true, requiredVersion: false },');
  L.push('          },');
  L.push('        })');
  L.push('      );');
  L.push('');
  L.push('      webpackConfig.module.rules.push({');
  L.push('        test: /\\.mjs$/,');
  L.push('        include: /node_modules/,');
  L.push('        type: "javascript/auto",');
  L.push('        resolve: { fullySpecified: false },');
  L.push('      });');
  L.push('');
  L.push('      if (webpackConfig.optimization) webpackConfig.optimization.sideEffects = false;');
  L.push('      else webpackConfig.optimization = { sideEffects: false };');
  L.push('      return webpackConfig;');
  L.push('    },');
  L.push('  },');
  L.push('};');
  return L.join('\n') + '\n';
}

export function emitCraco(feir, appDir) {
  const content = cracoFile(feir);
  const abs = path.join(appDir, 'craco.config.js');
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, 'utf8');
  return { written: ['craco.config.js'], summary: 'craco.config.js (federated)' };
}
