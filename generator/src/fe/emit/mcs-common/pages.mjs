/* ── entry point ─────────────────────────────────────────────────────── */

export function emitPages(feir, appDir) {
  const pages = listPages(feir);
  const written = [];
  const write = (rel, content) => {
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  const hub = feir.output?.mfe?.hub === true;
  for (const page of pages) {
    const model = buildResourceModel(page);
    write(`src/pages/${model.resourceKebab}/index.tsx`, listIndexFile(model, hub));
    // Some resources are read-only (list/retrieve/delete only, e.g. TMF921 IntentReport -
    // no create/update operation in the spec at all) - don't emit a dialog with 0 fields
    // pointing at a create endpoint that doesn't exist.
    if (model.addForm) {
      write(`src/pages/${model.resourceKebab}/Create${model.ResourceName}Dialog.tsx`, createDialogFile(model));
    }
    write(`src/pages/${model.resourceKebab}/${model.ResourceName}DetailPage.tsx`, detailPageFile(model));
  }

  return { written, summary: `pages: ${pages.length} resource(s)` };
}
