function computedFromRules(fields) {
  return fields.filter((f) => f.computedFrom).map((f) => ({ target: f.name, source: f.computedFrom }));
}

function payloadSpecConsts(model) {
  const repeatableItemPayloads = {};
  const computedFromRepeatable = {};
  for (const f of model.addFields) {
    if (f.type === 'repeatable-group') {
      if (f.itemPayload) repeatableItemPayloads[f.name] = f.itemPayload;
      const rules = computedFromRules(f.itemFields ?? []);
      if (rules.length) computedFromRepeatable[f.name] = rules;
    }
  }
  return {
    add: JSON.stringify(model.addForm?.api?.payload ?? {}, null, 2),
    itemPayloads: JSON.stringify(repeatableItemPayloads, null, 2),
    computedFromRoot: JSON.stringify(computedFromRules(model.addFields), null, 2),
    computedFromRepeatable: JSON.stringify(computedFromRepeatable, null, 2),
  };
}

function gridColumnsLiteral(model) {
  const cols = (model.list.columns ?? []).filter((c) => c.type !== 'row-actions');
  const lines = cols.map((c) => {
    if (c.render === 'tag-count') {
      return `  { key: ${JSON.stringify(c.field)}, label: ${JSON.stringify(c.label ?? c.field)}, sortable: ${!!c.sortable}, render: (row: any) => Array.isArray(row.${c.field}) ? row.${c.field}.length : (row.${c.field} ?? '-') },`;
    }
    return `  { key: ${JSON.stringify(c.field)}, label: ${JSON.stringify(c.label ?? c.field)}, sortable: ${!!c.sortable} },`;
  });
  return `[\n${lines.join('\n')}\n]`;
}

