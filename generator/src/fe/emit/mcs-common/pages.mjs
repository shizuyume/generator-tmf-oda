function detailFieldsJsx(fields) {
  return fields.map((f) => {
    if (typeof f === 'string') return `            <DetailField label={${JSON.stringify(f)}} value={data.${f}} />`;
    const accessor = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(f.field) ? `data.${f.field}` : `data[${JSON.stringify(f.field)}]`;
    if (f.render === 'link') return `            <DetailField label={${JSON.stringify(f.label ?? f.field)}} value={${accessor} ? <a href={${accessor}}>{${accessor}}</a> : undefined} />`;
    return `            <DetailField label={${JSON.stringify(f.label ?? f.field)}} value={${accessor}} />`;
  }).join('\n');
}

function tableBlockJsx(block, tabVarName) {
  const cols = block.columns ?? [];
  const renderCols = block.renderColumns ?? [];
  const viewToggle = block.viewToggle === true;
  const stateVar = `${tabVarName}View`;
  const setStateVar = `set${toPascalCase(tabVarName)}View`;
  const cardRows = `            <Stack spacing={1.5}>
              {(${block.field}Items).map((item: any, idx: number) => (
                <Box key={item.id ?? idx} sx={{ p: 2, border: '1px solid #e2e8f0', borderRadius: 2, bgcolor: '#f8fafc' }}>
                  <Box sx={DETAIL_GRID_SX}>
${[...cols.map((c) => `                    <DetailField label={${JSON.stringify(c)}} value={item[${JSON.stringify(c)}]} />`),
     ...renderCols.map((rc) => `                    <DetailField label={${JSON.stringify(rc.label ?? rc.field)}} value={item[${JSON.stringify(rc.field)}]?.[${JSON.stringify(rc.sub)}]} />`)].join('\n')}
                  </Box>
                </Box>
              ))}
            </Stack>`;
  const tableCells = [...cols.map((c) => ({ label: c, expr: `row[${JSON.stringify(c)}]` })),
    ...renderCols.map((rc) => ({ label: rc.label ?? rc.field, expr: `row[${JSON.stringify(rc.field)}]?.[${JSON.stringify(rc.sub)}]` }))];
  const tableRows = `            <TableContainer>
              <Table size="small">
                <TableHead>
                  <TableRow>
${tableCells.map((c) => `                    <TableCell>${c.label}</TableCell>`).join('\n')}
                  </TableRow>
                </TableHead>
                <TableBody>
                  {(${block.field}Items).map((row: any, idx: number) => (
                    <TableRow key={row.id ?? idx}>
${tableCells.map((c) => `                      <TableCell>{${c.expr} ?? '-'}</TableCell>`).join('\n')}
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            </TableContainer>`;
  const empty = `            <CustomTypography variant="body2" color="text.secondary">${block.emptyState?.title ?? 'No data.'}</CustomTypography>`;
  if (!viewToggle) {
    return `          {(${block.field}Items).length === 0 ? (\n${empty}\n          ) : (\n${cardRows}\n          )}`;
  }
  return `          {(${block.field}Items).length === 0 ? (
${empty}
          ) : ${stateVar} === 'card' ? (
${cardRows}
          ) : (
${tableRows}
          )}`;
}

