function relationHookVarName(field, ownerFieldName) {
  const base = ownerFieldName ? `${ownerFieldName}${toPascalCase(field.name)}` : field.name;
  return `${toCamelCase(base)}Search`;
}

/** {resource -> hookVar} for every relation field reachable from `fields` (top-level + one
 * level of repeatable nesting - matches TMF736's actual shape, no deeper nesting needed). */
function collectHookVars(fields) {
  const list = [];
  for (const f of fields) {
    if (f.relation) list.push({ field: f, hookVar: relationHookVarName(f, null) });
    if (f.type === 'repeatable-group') {
      for (const itf of f.itemFields ?? []) {
        if (itf.relation) list.push({ field: itf, hookVar: relationHookVarName(itf, f.name) });
      }
    }
  }
  return list;
}

