// emit/mcs-common/types.mjs — types/<resource>.ts per list page (TMF wire shape).
// Interface fields are derived from the ADD form's api.payload spec (the wire keys a
// create request actually sends), which is the most reliable source of the true API
// property names (form field NAMES are form-state identifiers like `atType`, but the
// payload spec's left-hand keys are the real wire keys like `@type`).
import fs from 'node:fs';
import path from 'node:path';
import { toPascalCase } from './naming.mjs';
import { buildResourceModel, listPages } from './resourceModel.mjs';

const BANNER = '// GENERATED by fe-gen emit mcs-common - DO NOT EDIT. Re-run `fe-gen emit` instead.';

function fieldByName(fields, name) {
  return fields.find((f) => f.name === name);
}

function tsTypeForField(f) {
  if (!f) return 'string';
  switch (f.type) {
    case 'number-input': return 'number';
    case 'toggle':
    case 'checkbox': return 'boolean';
    default: return 'string';
  }
}

/** One payload-spec object -> [{wireKey, tsType, optional}]. Nested objects/repeatable
 * arrays recurse; `item.X` tokens resolve against `itemFields` when walking an itemPayload. */
function walkPayloadSpec(spec, fields) {
  const props = [];
  for (const [wireKey, node] of Object.entries(spec ?? {})) {
    if (typeof node === 'string') {
      const m = /^(fields|item)\.(.+)$/.exec(node);
      const fieldName = m ? m[2] : node;
      const f = fieldByName(fields, fieldName);
      if (f && f.type === 'repeatable-group') {
        const itemProps = f.itemPayload
          ? walkPayloadSpec(f.itemPayload, f.itemFields ?? [])
          : (f.itemFields ?? []).map((itf) => ({ wireKey: itf.name, tsType: tsTypeForField(itf), optional: !itf.required }));
        props.push({ wireKey, tsType: `${interfaceBody(itemProps)}[]`, optional: !f.required });
      } else {
        props.push({ wireKey, tsType: tsTypeForField(f), optional: !(f && f.required) });
      }
    } else if (node && typeof node === 'object') {
      const nested = walkPayloadSpec(node, fields);
      props.push({ wireKey, tsType: interfaceBody(nested), optional: true });
    }
  }
  return props;
}

function propLine(p) {
  const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(p.wireKey) ? p.wireKey : JSON.stringify(p.wireKey);
  return `  ${key}${p.optional ? '?' : ''}: ${p.tsType};`;
}

function interfaceBody(props) {
  return `{\n${props.map((p) => '  ' + propLine(p)).join('\n')}\n  }`;
}

function interfaceFile(props, name, extra = []) {
  const lines = [`export interface ${name} {`, ...props.map(propLine), ...extra, '}'];
  return lines.join('\n');
}

export function emitTypes(feir, appDir) {
  const pages = listPages(feir);
  const written = [];
  const write = (rel, content) => {
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  const exportNames = [];
  for (const page of pages) {
    const model = buildResourceModel(page);
    const createProps = walkPayloadSpec(model.addForm?.api?.payload ?? {}, model.addFields);
    const updateProps = walkPayloadSpec(model.editForm?.api?.payload ?? {}, model.editFields);

    // Read-only resources (no create/update op, e.g. TMF921 IntentReport) have no payload
    // spec to derive fields from at all - fall back to the detail page's description-list
    // block, which IS a response-shape source (also used as a supplement, not just
    // fallback, in case detail shows a response-only field the create payload never sends).
    const detailCardFields = (model.detail?.sections?.[0]?.tabs?.[0]?.blocks ?? [])
      .filter((b) => b.type === 'card' && b.layout === 'description-list')
      .flatMap((b) => b.fields ?? [])
      .map((f) => (typeof f === 'string' ? f : f.field))
      .filter((f) => f && !['id', 'href'].includes(f) && !createProps.some((p) => p.wireKey === f));
    const mainProps = [...createProps, ...detailCardFields.map((wireKey) => ({ wireKey, tsType: 'string', optional: true }))];

    const mainInterface = interfaceFile(
      mainProps,
      model.ResourceName,
      ['  id: string;', '  href?: string;'],
    );
    const fvoInterface = interfaceFile(createProps, `${model.ResourceName}_FVO`);
    const mvoInterface = interfaceFile(updateProps.length ? updateProps : createProps, `${model.ResourceName}_MVO`);

    const content = [
      BANNER,
      `// TMF wire shape for "${model.resourceName}" - derived from the add/edit form's api.payload spec.`,
      '',
      mainInterface,
      '',
      fvoInterface,
      '',
      mvoInterface,
      '',
    ].join('\n');
    write(`src/types/${model.resourceKebab}.ts`, content);
    exportNames.push(model.resourceKebab);
  }

  write('src/types/listParams.ts', [
    BANNER,
    'export interface ListParams {',
    '  offset?: number;',
    '  limit?: number;',
    '  fields?: string;',
    '  [key: string]: string | number | undefined;',
    '}',
    '',
    'export interface ListResponse<T> {',
    '  data: T[];',
    '  total: number;',
    '  resultCount: number;',
    '}',
    '',
  ].join('\n'));

  write('src/types/index.ts', [
    BANNER,
    ...exportNames.map((n) => `export * from './${n}';`),
    "export * from './listParams';",
    '',
  ].join('\n'));

  return { written, summary: `types: ${pages.length} resource(s)` };
}

export { walkPayloadSpec, tsTypeForField, toPascalCase };
