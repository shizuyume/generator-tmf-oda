/**
 * Emit form files untuk setiap page FEIR yang punya forms.add/edit.
 * @returns {{ written: string[], summary: string }}
 */
/** Warning eksplisit (F3): field yang payload-nya pakai transform TIDAK BISA di-inverse
 * saat edit (rootPrefillLiteral/collectItemTokens hanya mengenali token string) - field
 * itu dikosongkan di EditForm, bukan diam-diam. Satu warning per field yang terpengaruh. */
function collectTransformWarnings(pageId, payload) {
  const warnings = [];
  for (const [k, v] of Object.entries(payload ?? {})) {
    if (v && typeof v === 'object' && !Array.isArray(v) && '$src' in v) {
      if (v.$tx) warnings.push(`form ${pageId}: field "${k}" pakai transform "${v.$tx}" - prefill edit tidak dapat di-inverse, field dikosongkan`);
    } else if (v && typeof v === 'object' && !Array.isArray(v)) {
      warnings.push(...collectTransformWarnings(pageId, v));
    }
  }
  return warnings;
}

export function emitForms(feir, appDir) {
  if (feir.output?.mfe?.federationTemplate === 'common-remote') {
    // mcs-common owns form emission entirely (emit/mcs-common/pages.mjs's Create*Dialog) -
    // it renders relation/repeatable fields its own way (RefAutocompleteField, local
    // useFieldArray), not StandardFormModal's FieldSpec dispatch. See emit/mfe.mjs's guard.
    return { written: [], summary: 'form: federationTemplate=common-remote - delegasi ke emit/mcs-common (form.mjs dilewati)' };
  }
  // F3: form.mjs sebelumnya TIDAK PERNAH konsultasi adapter - field type apa pun lolos
  // ke StandardFormModal.tsx (dispatch statis), termasuk semantic yang UNSUPPORTED untuk
  // library aktif (mis. typeahead di fe-default/neudela). Beda dengan emit/page.mjs yang
  // sudah resolve() setiap kolom/tombol. Preflight ini menyamakan perlakuannya: field yang
  // adapter-nya throw UNSUPPORTED gagal SEKARANG (pesan jelas), bukan diam-diam jadi text
  // input generik saat runtime.
  const adapter = loadAdapter(feir.ui?.library ?? 'mui');
  const checkFieldSupport = (f, pointer) => {
    if (!f || f.reuse) return;
    adapter.resolve(f.type); // melempar bila UNSUPPORTED - pesan sudah baku dari adapter
    for (const [i, sub] of (f.itemFields ?? []).entries()) checkFieldSupport(sub, `${pointer}/itemFields/${i}`);
  };
  for (const page of feir.pages ?? []) {
    for (const kind of ['add', 'edit']) {
      for (const [i, f] of (page.forms?.[kind]?.fields ?? []).entries()) {
        checkFieldSupport(f, `/pages/${page.id}/forms/${kind}/fields/${i}`);
      }
    }
  }

  const written = [];
  const write = (rel, content) => {
    if (content.includes('\uFFFD')) {
      throw new Error(`emit/form: U+FFFD ditemukan di "${rel}" (mojibake guard) - berhenti`);
    }
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  let formPages = 0;
  const warnings = [];
  for (const page of feir.pages ?? []) {
    const forms = page.forms;
    if (!forms?.add && !forms?.edit) continue;
    const res = resourceInfo(page, feir);
    const eps = endpointsFor(feir, page);
    if (forms.add && !eps.create) {
      throw new Error(`emit/form: page ${page.id} bentuk add tapi FEIR tidak punya endpoint create (no invented endpoints)`);
    }
    if (forms.edit && (!eps.update || !eps.retrieve)) {
      throw new Error(`emit/form: page ${page.id} bentuk edit tapi FEIR tidak punya endpoint update/retrieve (no invented endpoints)`);
    }

    const addFieldDefs = forms.add?.fields ?? [];
    const addPayload = forms.add?.api?.payload ?? {};
    const editHasFields = (forms.edit?.fields ?? []).some((f) => f && !(f.reuse === 'add'));
    const editFieldDefs = editHasFields ? forms.edit.fields : addFieldDefs; // reuse: add
    const editPayload = forms.edit?.api?.payload ?? {};

    warnings.push(...collectTransformWarnings(page.id, addPayload));
    warnings.push(...collectTransformWarnings(page.id, editPayload));

    const addDefaults = defaultsForFields(addFieldDefs);
    const editDefaults = defaultsForFields(editFieldDefs);

    write(`src/pages/${page.id}/zodSchemas.ts`, zodSchemasFile(page, addFieldDefs, editFieldDefs, addDefaults, editDefaults, addPayload, editPayload));
    if (forms.add) write(`src/pages/${page.id}/AddForm.tsx`, addFormFile(feir, page, forms.add, res));
    if (forms.edit) write(`src/pages/${page.id}/EditForm.tsx`, editFormFile(feir, page, forms.edit, res));
    formPages += 1;
  }

  return {
    written: written.sort(),
    summary: `${formPages} form pair(s) -> src/pages/<id>/zodSchemas.ts + AddForm.tsx + EditForm.tsx`,
    warnings,
  };
}