const LUCIDE_PERMIT = new Set(['Eye', 'Pencil', 'Plus', 'Trash2']);

/** tone semantik -> props via adapter.resolve('button').propsMap (bukan vocab UI hardcode). */
function buttonPropsOf(adapter, tone) {
  const r = adapter.resolve('button', { tone });
  const mapped = typeof r.propsMap === 'function' ? r.propsMap({ tone }) : {};
  return Object.entries(mapped)
    .map(([k, v]) => `${k}=${q1(v)}`)
    .join(' ');
}

function pageFile(ir, page, res, adapter) {
  const list = page.list;
  const scheme = list.paginationScheme ?? list.pagination?.scheme ?? 'offset-limit';
  const debounce = list.search?.debounceMs ?? 300;
  const perPageOptions = list.pagination?.perPageOptions ?? [10, 25, 50];
  const defaultPageSize = typeof perPageOptions[0] === 'number' ? perPageOptions[0] : 10;
  const rowsActions = (list.columns ?? []).find((c) => c.type === 'row-actions');
  const dataColumns = (list.columns ?? []).filter((c) => c.type !== 'row-actions');
  const addAction = (page.actions ?? []).find((a) => a.action === 'open-form' && page.forms?.add);
  const detailPath = page.detail?.path ?? null;
  const hasDetail = !!detailPath && (rowsActions?.items ?? []).some((it) => it.action === 'open-detail');
  const hasEdit = (rowsActions?.items ?? []).some((it) => it.action === 'open-form');
  const hasDelete = (rowsActions?.items ?? []).some((it) => it.action === 'delete');
  const hasAddForm = !!page.forms?.add;
  const hasEditForm = !!page.forms?.edit;

  // ikon lucide yang benar-benar dipakai (permit set ketat; ikon tak dikenal -> FAIL)
  const icons = new Set();
  for (const it of rowsActions?.items ?? []) {
    if (!LUCIDE_PERMIT.has(it.icon)) throw new Error(`emit/page: icon row-action "${it.icon}" belum di-permit (lucide)`);
    icons.add(it.icon);
  }
  if (addAction?.icon) {
    if (!LUCIDE_PERMIT.has(addAction.icon)) throw new Error(`emit/page: icon toolbar "${addAction.icon}" belum di-permit (lucide)`);
    icons.add(addAction.icon);
  }
  const hasAdd = !!addAction;

  // queryParams FEIR -> binding list: literal '' -> param literal; {{search.q}} -> precompute q;
  // {{pagination.X}} -> resolveTemplate runtime (binding nama PERSIS dari FEIR resolvedBindings).
  const precompute = [];
  const args = [];
  const paramKeys = Object.keys(list.queryParams ?? {});
  for (const key of paramKeys) {
    const tpl = list.queryParams[key];
    if (tpl === '') {
      args.push(`${key}: ''`);
      continue;
    }
    const m = /^\{\{\s*(\w+\.\w+)\s*\}\}$/.exec(String(tpl));
    if (!m) {
      throw new Error(`emit/page: queryParams.${key} = ${tpl} tak bisa di-binding (resmi: {{search.q}} / {{pagination.offset|limit|page|perPage}} / literal)`);
    }
    const [ns, ref] = m[1].split('.');
    if (ns === 'search' && ref === 'q') {
      precompute.push('  let q: string | undefined = params.q;');
      precompute.push('  if (q !== undefined && q !== \'\') {');
      precompute.push("    q = resolveTemplate('{{search.q}}', { search: { q } });");
      precompute.push('  }');
      args.push('q');
    } else if (ns === 'pagination') {
      const src = ref === 'page' ? 'params.page' : ref === 'perPage' ? 'params.perPage' : ref === 'offset' ? 'params.offset' : 'params.limit';
      const fallback = ref === 'offset' || ref === 'page' ? 0 : defaultPageSize;
      args.push(
        `${key}: Number(resolveTemplate('{{pagination.${ref}}}', { pagination: { ${ref}: ${src} ?? ${fallback} } }))`,
      );
    } else {
      throw new Error(`emit/page: queryParams.${key} memakai namespace "${ns}" - list emitter hanya search.q + pagination.*`);
    }
  }

  const L = [];
  L.push(BANNER);
  L.push(`// Halaman list ${page.id} (view: list). Assembly runtime: useCrudPage + StandardList + api defs.`);
  L.push('// Komponen UI = barrel src/gen/ui.tsx (adapter.resolve) - tanpa import MUI langsung.');
  L.push('// Titik sambung form/detail: emit/form.mjs dan emit/detail.mjs (todo berikutnya).');
  L.push('// modal add/edit di-buka dari sini via emit/form.mjs (state addOpen/editId).');
  L.push('');
  L.push("import { ComponentProps, ReactElement, useState } from 'react';");
  if (hasDetail) L.push("import { useNavigate } from 'react-router-dom';");
  L.push(`import { ${[...icons].join(', ')} } from 'lucide-react';`);
  L.push("import type { ListParams, Severity } from '../../gen/useCrudPage';");
  L.push("import { useCrudPage } from '../../gen/useCrudPage';");
  L.push("import { resolveTemplate } from '../../gen/QueryContext';");
  L.push("import { StandardList } from '../../gen/StandardList';");
  // Daftar CRUD di-import SETELAH body selesai dan disaring ke yang benar-benar
  // dipakai (lihat pengisian CRUD_IMPORT_SLOT di akhir pageFile). Dulu kelimanya
  // di-import tanpa syarat, sehingga halaman list tanpa aksi "view" tetap membawa
  // get<Res>() yang tak terpakai - eslint no-unused-vars, melanggar "tidak
  // menghasilkan unused import" (requirement doc §21).
  L.push(CRUD_IMPORT_SLOT);
  L.push(`import type { ${res.pascal} } from ${q1(`../../gen/api/${res.kebab}`)};`);
  L.push(UI_IMPORT_SLOT);
  const mui = (ir.ui?.library ?? 'mui') === 'mui';
  if (list.filters?.length) {
    // F6: UiSelect BUKAN bagian BARREL_MEMBERS/x-semantic-vocabulary (filter list, bukan
    // form field) - fe-default/neudela sudah mengekspornya langsung dari uiwrappers.tsx,
    // tapi barrel ui.tsx generik (BARREL_MEMBERS) tidak meneruskannya. Import langsung dari
    // uiwrappers, bukan lewat ui.tsx, supaya BARREL_MEMBERS/mui tidak perlu tahu soal filter.
    if (mui) {
      L.push("import { MenuItem as MuiFilterMenuItem, Select as MuiFilterSelect } from '@mui/material';");
    } else {
      L.push("import { UiSelect } from '../../gen/uiwrappers';");
    }
  }
  if (hasAddForm) L.push("import AddForm from './AddForm';");
  if (hasEditForm) L.push("import EditForm from './EditForm';");
  L.push('');
  L.push('export default function List(): ReactElement {');
  if (hasDetail) L.push('  const navigate = useNavigate();');
  L.push('  const [snack, setSnack] = useState<{ message: string; severity: Severity } | null>(null);');
  if (hasAddForm) L.push('  const [addOpen, setAddOpen] = useState(false);');
  if (hasEditForm) L.push('  const [editId, setEditId] = useState<string | number | null>(null);');
  L.push('');
  L.push('  const notify = (message: string, severity: Severity): void => {');
  L.push('    setSnack({ message, severity });');
  L.push('  };');
  L.push('');
  if (hasAddForm) {
    L.push('  // modal add di-assembly emit/form.mjs - dikontrol state addOpen.');
    L.push('  const openAdd = (): void => {');
    L.push('    setAddOpen(true);');
    L.push('  };');
    L.push('');
  }
  if (hasEditForm) {
    L.push('  // modal edit di-assembly emit/form.mjs - dikontrol state editId.');
    L.push('  const openEdit = (id: string | number): void => {');
    L.push('    setEditId(id);');
    L.push('  };');
    L.push('');
  }
  if (hasDetail) {
    L.push('  // detail page di-assembly emit/detail.mjs (todo berikutnya) - route sudah nyata.');
    L.push('  const openDetail = (id: string | number): void => {');
    L.push(`    navigate(${q1(detailPath)}.replace(':id', String(id)));`);
    L.push('  };');
    L.push('');
  }
  L.push(`  const crud = useCrudPage<${res.pascal}>(`);
  L.push('    {');
  L.push('      list: async (params: ListParams) => {');
  for (const p of precompute) L.push(p);
  if (args.length) {
    L.push(`        const result = await list${res.pascal}({`);
    for (const a of args) L.push(`          ${a},`);
    L.push('        });');
  } else {
    L.push(`        const result = await list${res.pascal}({});`);
  }
  L.push('        return { rows: result.rows, total: result.total };');
  L.push('      },');
  L.push(`      create: (payload) => create${res.pascal}(payload),`);
  L.push(`      update: (id, payload) => update${res.pascal}(id, payload),`);
  L.push(`      remove: (id) => delete${res.pascal}(id),`);
  L.push("      getRowId: (row) => row.id ?? row.href ?? '',");
  L.push('    },');
  L.push('    {');
  L.push(`      scheme: ${q1(scheme)},`);
  L.push(`      searchDebounceMs: ${debounce},`);
  L.push(`      defaultPageSize: ${defaultPageSize},`);
  L.push('      notify,');
  L.push('    },');
  L.push('  );');
  L.push('');
  if (hasDelete) {
    L.push('  const confirmDelete = (id: string | number): void => {');
    L.push("    if (window.confirm('Hapus data ini? Klik OK untuk melanjutkan.')) {");
    L.push('      void crud.remove(id);');
    L.push('    }');
    L.push('  };');
    L.push('');
  }
  L.push("  const columns: ComponentProps<typeof StandardList>['columns'] = [");
  for (const col of dataColumns) L.push(columnCode(col));
  L.push('  ];');
  L.push('');
  L.push('  return (');
  L.push("    <UiBox sx={{ display: 'flex', flexDirection: 'column', gap: 1, height: '100%', minHeight: '60vh' }}>");
  L.push('      <StandardList');
  L.push('        columns={columns}');
  L.push('        rows={crud.rows}');
  L.push('        rowCount={crud.rowCount}');
  L.push('        pageModel={crud.pagination}');
  L.push('        sortModel={crud.sort}');
  L.push('        filterModel={crud.filter}');
  L.push('        onPaginationModelChange={crud.setPagination}');
  L.push('        onSortModelChange={crud.setSort}');
  L.push('        onFilterModelChange={crud.setFilter}');
  L.push('        loading={crud.loading}');
  L.push('        getRowId={(row) => row.id ?? row.href ?? \'\'}');;
  L.push(`        pageSizeOptions={[${perPageOptions.join(', ')}]}`);
  if (list.emptyState?.title) L.push(`        emptyText={${q1(list.emptyState.title)}}`);
  // emptyState.action (schema $defs.emptyAction: {label, open}) -> tombol di baris kosong
  // (F1: requirement doc §16 "empty state punya action"). `open` HANYA didukung untuk form
  // add (satu-satunya modal yang emptyState punya alasan membuka) - form lain diabaikan diam
  // -diam TIDAK boleh, jadi kita hanya emit prop bila hasAddForm, dan JANGAN emit sama sekali
  // (bukan emit lalu onClick no-op) bila form yang dirujuk tidak ada.
  if (list.emptyState?.action && hasAddForm) {
    L.push(`        emptyAction={{ label: ${q1(list.emptyState.action.label)}, onClick: () => setAddOpen(true) }}`);
  }
  if (list.search?.enabled || list.filters?.length) {
    // Bungkus fragment HANYA bila lebih dari satu elemen (search + >=1 filter, atau >=2
    // filter) - search-saja (kasus SEMUA golden hari ini) tetap satu baris seperti sebelum
    // F6, supaya spec tanpa list.filters byte-identik persis (golden-neutral).
    const needsFragment = (list.search?.enabled ? 1 : 0) + (list.filters?.length ?? 0) > 1;
    L.push('        searchField={');
    if (needsFragment) L.push('          <>');
    const indent = needsFragment ? '            ' : '          ';
    if (list.search?.enabled) {
      L.push(`${indent}<UiTextField size="small" placeholder={${q1(list.search.placeholder ?? 'Cari...')}} value={crud.searchQ} onChange={(e) => crud.setSearchQ(e.target.value)} sx={{ width: 260 }} />`);
    }
    // list.filters (F6): tiap entry {field,label,type:select,options} -> satu Select yang
    // menulis ke useCrudPage.extra[field] (house filter - sudah lama ada di query params,
    // sebelum F6 tak pernah ada UI yang mengisinya). Ganti filter -> reset ke halaman 0.
    // UiSelect (fe-default/neudela lewat uiwrappers) dan MUI Select+MenuItem (import
    // langsung, DI LUAR barrel semantic - filter list bukan bagian x-semantic-vocabulary,
    // dan MUI Select mentah butuh children MenuItem, kontrak berbeda dari UiSelect) dipisah
    // di sini karena kontraknya genuinely berbeda, bukan sekadar variasi styling.
    for (const filt of list.filters ?? []) {
      const onChangeStmt = `{ crud.setExtra((x) => ({ ...x, ${q1(filt.field)}: v || undefined })); crud.setPagination((p) => ({ ...p, page: 0 })); }`;
      if (mui) {
        L.push(`${indent}<MuiFilterSelect size="small" label={${q1(filt.label)}} value={crud.extra[${q1(filt.field)}] ?? ''} onChange={(e) => { const v = e.target.value; ${onChangeStmt} }} sx={{ minWidth: 160 }}>`);
        L.push(`${indent}  <MuiFilterMenuItem value="">{${q1(`Semua ${filt.label}`)}}</MuiFilterMenuItem>`);
        for (const [value, label] of Object.entries(filt.options ?? {})) {
          L.push(`${indent}  <MuiFilterMenuItem value=${q1(value)}>{${q1(label)}}</MuiFilterMenuItem>`);
        }
        L.push(`${indent}</MuiFilterSelect>`);
      } else {
        const opts = Object.entries(filt.options ?? {}).map(([value, label]) => `{ value: ${q1(value)}, label: ${q1(label)} }`);
        L.push(`${indent}<UiSelect label={${q1(filt.label)}} placeholder={${q1(`Semua ${filt.label}`)}} value={crud.extra[${q1(filt.field)}] ?? ''} options={[${opts.join(', ')}]} onChange={(v) => ${onChangeStmt}} />`);
      }
    }
    if (needsFragment) L.push('          </>');
    L.push('        }');
  }
  if (hasAdd) {
    const btnProps = buttonPropsOf(adapter, addAction.variant ?? 'primary');
    L.push('        toolbarActions={');
    L.push(`          <UiButton ${btnProps} startIcon={<Plus size={16} />} onClick={openAdd}>{${q1(addAction.label)}}</UiButton>`);
    L.push('        }');
  }
  if (rowsActions?.items?.length) {
    L.push('        rowActions={(row) => (');
    L.push("          <UiBox sx={{ display: 'flex', gap: 0.5 }}>");
    for (const it of rowsActions.items) {
      const icon = String(it.icon);
      const lbl = it.label ?? icon;
      const open = it.action === 'open-detail' && hasDetail ? 'openDetail' : it.action === 'open-form' && hasEditForm ? 'openEdit' : it.action === 'delete' && hasDelete ? 'confirmDelete' : null;
      if (open) {
        L.push(`            <UiIconButton size="small" title={${q1(lbl)}} aria-label={${q1(lbl)}} onClick={() => ${open}(row.id as string)}><${icon} size={16} /></UiIconButton>`);
      }
    }
    L.push('          </UiBox>');
    L.push('        )');
    L.push('        }');
  }
  L.push('      />');
  L.push('      <UiSnackbar');
  L.push('        open={snack !== null}');
  L.push('        autoHideDuration={4000}');
  L.push('        onClose={() => setSnack(null)}');
  L.push("        anchorOrigin={{ vertical: 'bottom', horizontal: 'left' }}");
  L.push('      >');
  L.push("        <UiAlert severity={snack?.severity ?? 'info'} onClose={() => setSnack(null)} variant=\"filled\">");
  L.push('          {snack?.message}');
  L.push('        </UiAlert>');
  L.push('      </UiSnackbar>');
  if (hasAddForm) {
    L.push(`      <AddForm open={addOpen} onClose={() => setAddOpen(false)} onSaved={() => { void crud.reload(); notify('Data berhasil dibuat', 'success'); }} />`);
  }
  if (hasEditForm) {
    L.push(`      <EditForm open={editId !== null} id={editId ?? 0} onClose={() => setEditId(null)} onSaved={() => { void crud.reload(); notify('Data berhasil diperbarui', 'success'); }} />`);
  }
  L.push('    </UiBox>');
  L.push('  );');
  L.push('}');
  L.push('');

  // Isi slot import CRUD: hanya nama yang benar-benar muncul di body (di luar baris
  // slot itu sendiri). Disaring dari TEKS hasil, bukan dari kondisi yang menyusun
  // body, supaya tidak bisa drift saat body berubah.
  const slot = L.indexOf(CRUD_IMPORT_SLOT);
  const uiSlot = L.indexOf(UI_IMPORT_SLOT);
  const bodyText = L.filter((_, i) => i !== slot && i !== uiSlot).join('\n');
  const usedApi = ['create', 'delete', 'get', 'list', 'update']
    .map((op) => `${op}${res.pascal}`)
    .filter((name) => new RegExp(`\\b${name}\\b`).test(bodyText));
  L[slot] = `import { ${usedApi.join(', ')} } from ${q1(`../../gen/api/${res.kebab}`)};`;
  // Sama pola dengan slot CRUD di atas: saring barrel Ui* dari teks body yang SUDAH jadi,
  // bukan dari kondisi penyusunnya - dulu barrel ini diimpor tanpa syarat (UiButton/UiChip/
  // UiIconButton/UiTextField/UiTooltip/UiTypography lolos ke halaman yang tak memakainya
  // sama sekali), menghasilkan eslint no-unused-vars di setiap list page tanpa search/row
  // action/kolom truncated.
  const uiCandidates = ['UiAlert', 'UiBox', 'UiButton', 'UiChip', 'UiIconButton', 'UiSnackbar', 'UiTextField', 'UiTooltip', 'UiTypography'];
  const usedUi = uiCandidates.filter((name) => new RegExp(`\\b${name}\\b`).test(bodyText));
  L[uiSlot] = `import { ${usedUi.join(', ')} } from '../../gen/ui';`;

  return L.join('\n');
}

