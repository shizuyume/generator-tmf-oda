function apiFile(ir, page) {
  const res = resourceInfo(page, ir);
  const base = resolveApiPath(page.list.api, ir);
  const eps = ir.api?.endpoints ?? {};
  const listParams = page.list?.queryParams ?? {};

  // F5: apiRef pada forms.add/edit -> tipe request registry (ir.apis), MENGGANTIKAN
  // Record<string, unknown> generik. Golden-neutral: page tanpa apiRef (semua spec hari
  // ini) mengambil jalur lama persis.
  const apiByName = new Map((ir.apis ?? []).map((a) => [a.name, a]));
  const addApi = page.forms?.add?.api?.ref ? apiByName.get(page.forms.add.api.ref) : null;
  const editApi = page.forms?.edit?.api?.ref ? apiByName.get(page.forms.edit.api.ref) : null;
  const addPayloadType = addApi?.request?.body ? `${pascal(page.forms.add.api.ref)}Request` : 'Record<string, unknown>';
  const editPayloadType = editApi?.request?.body ? `${pascal(page.forms.edit.api.ref)}Request` : 'Record<string, unknown>';
  const registryTypeImports = [...new Set([
    addApi?.request?.body ? addPayloadType : null,
    editApi?.request?.body ? editPayloadType : null,
  ].filter(Boolean))];

  const L = [];
  L.push(BANNER);
  L.push(`// Api defs ${res.pascal} dari FEIR api.endpoints (${ir.source}).`);
  L.push('// Method HANYA untuk endpoint yang ADA di FEIR - tidak meng-invent endpoint.');
  L.push('// Path = {{api.basePath}} di-resolve emit-time ke ir.api.basePath (bindingSources.api, M2).');
  L.push('');
  L.push("import { apiRequest } from '../apiClient';");
  L.push("import type { ApiEnvelope } from '../apiClient';");
  if (registryTypeImports.length) {
    L.push(`import type { ${registryTypeImports.join(', ')} } from './types.generated';`);
  }
  L.push('');
  L.push(`const RES_BASE = ${q1(base)};`);
  L.push('');
  L.push(`export interface ${res.pascal} {`);
  L.push('  id?: string;');
  L.push('  href?: string;');
  L.push('  name?: string;');
  L.push('  description?: string;');
  L.push('  [key: string]: unknown;');
  L.push('}');
  L.push('');

  if (eps.list) {
    L.push(`export interface List${res.pascal}Params {`);
    for (const k of Object.keys(listParams)) L.push(`  ${k}?: ${paramTypeOf(k)};`);
    if (!Object.keys(listParams).length) L.push('  [key: string]: unknown;');
    L.push('}');
    L.push('');
    L.push(`export interface List${res.pascal}Result {`);
    L.push(`  rows: ${res.pascal}[];`);
    L.push('  total: number;');
    L.push('}');
    L.push('');
    L.push(`export async function list${res.pascal}(params: List${res.pascal}Params = {}): Promise<List${res.pascal}Result> {`);
    L.push(`  const envelope: ApiEnvelope<${res.pascal}[]> = await apiRequest(RES_BASE, { method: 'GET', params: { ...params } });`);
    L.push('  const rows = envelope.data ?? [];');
    L.push('  return { rows, total: envelope.total ?? rows.length };');
    L.push('}');
    L.push('');
  }
  if (eps.retrieve) {
    L.push(`export async function get${res.pascal}(id: string | number): Promise<${res.pascal} | null> {`);
    L.push(`  const envelope: ApiEnvelope<${res.pascal}> = await apiRequest(RES_BASE + '/' + String(id), { method: 'GET' });`);
    L.push('  return envelope.data;');
    L.push('}');
    L.push('');
  }
  if (eps.create) {
    L.push(`export async function create${res.pascal}(payload: ${addPayloadType}): Promise<${res.pascal} | null> {`);
    L.push(`  const envelope: ApiEnvelope<${res.pascal}> = await apiRequest(RES_BASE, { method: 'POST', body: payload });`);
    L.push('  return envelope.data;');
    L.push('}');
    L.push('');
  }
  if (eps.update) {
    L.push(`export async function update${res.pascal}(id: string | number, payload: ${editPayloadType}): Promise<${res.pascal} | null> {`);
    L.push(`  const envelope: ApiEnvelope<${res.pascal}> = await apiRequest(RES_BASE + '/' + String(id), { method: 'PATCH', body: payload });`);
    L.push('  return envelope.data;');
    L.push('}');
    L.push('');
  }
  if (eps.delete) {
    L.push(`export async function delete${res.pascal}(id: string | number): Promise<void> {`);
    L.push(`  await apiRequest<never>(RES_BASE + '/' + String(id), { method: 'DELETE' });`);
    L.push('}');
    L.push('');
  }
  return L.join('\n');
}

function paramTypeOf(key) {
  switch (key) {
    case 'offset':
    case 'limit':
    case 'page':
    case 'perPage':
      return 'number';
    default:
      return 'string';
  }
}

/* ---------- render functions per kolom (via barrel UI; render kind tak dikenal -> FAIL) ---------- */

function renderCellFor(col) {
  const render = col.render;
  if (!render) return '';
  switch (render) {
    case 'truncated':
      return [
        '  renderCell: (params) => (',
        "    <UiTooltip title={String(params.value ?? '')}>",
        "      <UiTypography noWrap sx={{ maxWidth: 260, overflow: 'hidden', textOverflow: 'ellipsis' }}>",
        "        {String(params.value ?? '')}",
        '      </UiTypography>',
        '    </UiTooltip>',
        '  ),',
      ].join('\n');
    case 'tag-count':
      return [
        '  renderCell: (params) => {',
        '    const count = Array.isArray(params.value) ? params.value.length : 0;',
        '    return <UiChip size="small" label={String(count)} />;',
        '  },',
      ].join('\n');
    case 'tag':
      return [
        "  renderCell: (params) => <UiChip size=\"small\" label={String(params.value ?? '')} />,",
      ].join('\n');
    case 'date':
      return [
        "  valueFormatter: (value) => (value == null ? '' : new Date(String(value)).toLocaleString()),",
      ].join('\n');
    case 'link':
      return [
        '  renderCell: (params) => (',
        "    <a href={String(params.value ?? '')} target=\"_blank\" rel=\"noreferrer\" style={{ color: 'inherit' }}>",
        "      {String(params.value ?? '')}",
        '    </a>',
        '  ),',
      ].join('\n');
    default:
      throw new Error(`emit/page: render kind "${render}" tak dikenal (resmi: truncated|tag-count|tag|date|link)`);
  }
}

function columnCode(col) {
  const L = ['  {'];
  L.push(`    field: ${q1(col.field)},`);
  L.push(`    headerName: ${q1(col.label ?? col.field)},`);
  L.push(`    sortable: ${!!col.sortable},`);
  L.push('    filterable: false,');
  if (col.render) L.push(renderCellFor(col));
  L.push('  },');
  return L.join('\n');
}

