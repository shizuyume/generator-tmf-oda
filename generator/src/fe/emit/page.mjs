/**
 * Emit list pages + api defs + routes untuk semua page `view: list` di FEIR.
 * @returns {{ written: string[], summary: string }}
 */
export function emitPages(feir, appDir) {
  const listPages = (feir.pages ?? []).filter((p) => p.view === 'list');
  // T4 (F7): routablePages = list ∪ dashboard - keduanya butuh route+menu. Dashboard.tsx
  // SENDIRI ditulis emit/dashboard.mjs (kind terpisah); emitPages hanya perlu TAHU pages
  // ini ada supaya routes.tsx/ui.tsx/bootstrap.tsx tidak lagi gate ke list-saja (bug lama:
  // spec dashboard-tanpa-list akan menghasilkan app tanpa router sama sekali).
  const dashboardPages = (feir.pages ?? []).filter((p) => p.view === 'dashboard');
  const routablePages = [...listPages, ...dashboardPages];
  const adapter = loadAdapter(feir.ui?.library ?? 'mui');
  const written = [];
  const write = (rel, content) => {
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  for (const page of listPages) {
    const res = resourceInfo(page, feir);
    write(`src/gen/api/${res.kebab}.ts`, apiFile(feir, page));
    write(`src/pages/${page.id}/List.tsx`, pageFile(feir, page, res, adapter));
  }
  if (routablePages.length) {
    write('src/gen/ui.tsx', barrelSource(feir));
    write('src/gen/routes.tsx', routesFile(feir, routablePages));
    write('src/bootstrap.tsx', bootstrapFile());
  }

  return {
    written: written.sort(),
    summary: `${listPages.length} list page(s) + ${dashboardPages.length} dashboard page(s) routed -> src/pages/<id>/List.tsx + src/gen/api/<resource>.ts (+ routes/ui/bootstrap)`,
  };
}