// F7: UiStatCard HANYA ditambahkan ke barrel fe-default, dan HANYA bila FEIR punya
// halaman dashboard - menjaga 3 golden lama (tanpa dashboard) byte-identik. MUI/neudela
// TIDAK PERNAH menambahkan UiStatCard: keduanya 'fallback' (bukan 'covered'), dan
// adapter.resolve('stat-card') untuk mui hanya mengembalikan Card MENTAH (bukan komponen
// berprop label/value/trend) - dashboard.mjs merakit stat card dari UiCard+UiTypography
// yang SUDAH ada di barrel untuk mui/neudela, bukan lewat simbol UiStatCard.
function barrelMembersFor(feir, library) {
  const hasDashboard = (feir.pages ?? []).some((p) => p.view === 'dashboard');
  if (hasDashboard && library === 'fe-default') {
    return [...BARREL_MEMBERS, ['UiStatCard', 'stat-card']];
  }
  return BARREL_MEMBERS;
}

function barrelSource(feir) {
  const library = feir.ui?.library ?? 'mui';
  const members = barrelMembersFor(feir, library);
  if (UIWRAPPERS_LIBRARIES.has(library)) {
    const L = [];
    L.push(BANNER);
    L.push(`// Barrel ${library.toUpperCase()}: re-export wrapper di template runtime (src/gen/uiwrappers.tsx).`);
    L.push('// Komponen nyata dipakai di uiwrappers - tanpa import lib eksternal dari halaman.');
    L.push('');
    L.push(`export { ${members.map(([sym]) => sym).join(', ')} } from './uiwrappers';`);
    return L.join('\n') + '\n';
  }
  const adapter = loadAdapter(library);
  const L = [];
  L.push(BANNER);
  L.push(`// Barrel komponen UI di-resolve via generator/libs/${library}.adapter.js (semantic -> modul UI).`);
  L.push('// Box/Typography/Tooltip/Alert/Snackbar = assembly runtime (kontrak fallback adapter).');
  L.push('// Halaman src/pages/ memakai barrel ini - tanpa import UI langsung.');
  L.push('');
  // import/first (react-app eslintConfig): SEMUA import di atas, SEMUA export di bawah.
  const resolved = members.map(([sym, key]) => {
    let mod;
    let exp;
    if (ASSEMBLY_SET.has(key)) {
      mod = (library === 'mui' ? `@mui/material/${key}` : key);
      exp = key;
    } else {
      const r = adapter.resolve(key, {});
      mod = r.module;
      exp = r.export;
    }
    return { sym, exp, mod };
  });
  for (const { exp, mod } of resolved) L.push(`import ${exp} from '${mod}';`);
  L.push('');
  for (const { sym, exp } of resolved) L.push(`export const ${sym} = ${exp};`);
  return L.join('\n') + '\n';
}

