function routesFile(feir, routablePages) {
  const L = [];
  L.push(BANNER);
  L.push('// Routes lazy + menu sidebar dari pages FEIR (view: list). Di-wire src/bootstrap.tsx.');
  L.push('');
  L.push("import { lazy, ReactNode, Suspense } from 'react';");
  L.push("import { Route } from 'react-router-dom';");
  L.push("import type { MenuItemDef } from '../App';");
  L.push("import { UiBox, UiTypography } from './ui';");
  L.push('');
  // T4 (F7): routablePages = list ∪ dashboard - komponen halaman berbeda nama file per
  // view (List.tsx vs Dashboard.tsx), tapi keduanya butuh route + entri menu.
  const names = [];
  for (const p of routablePages) {
    const kind = p.view === 'dashboard' ? 'Dashboard' : 'List';
    const name = `${pascalKebab(p.id)}${kind}`;
    names.push([p, name]);
    L.push(`const ${name} = lazy(() => import('../pages/${p.id}/${kind}'));`);
  }
  // detail route: page.detail.path (mis. /party-rev-sharing-algorithms/:id) - hanya list page
  const detailNames = [];
  for (const p of routablePages) {
    if (p.view !== 'list' || !p.detail?.path) continue;
    const name = `${pascalKebab(p.id)}Detail`;
    detailNames.push([p, name]);
    L.push(`const ${name} = lazy(() => import('../pages/${p.id}/Detail'));`);
  }
  L.push('');
  L.push('export const appRoutes: ReactNode = (');
  L.push('  <>');
  for (const [p, name] of names) {
    const routeAttr = p.path === '/' ? 'index' : `path=${q1(p.path)}`;
    L.push(`    <Route ${routeAttr}`);
    L.push('      element={');
    L.push('        <Suspense');
    L.push("          fallback={<UiBox sx={{ p: 4 }}><UiTypography>Memuat...</UiTypography></UiBox>}");
    L.push(`        ><${name} /></Suspense>`);
    L.push('      }');
    L.push('    />');
  }
  for (const [p, name] of detailNames) {
    L.push(`    <Route path=${q1(p.detail.path)}`);
    L.push('      element={');
    L.push('        <Suspense');
    L.push("          fallback={<UiBox sx={{ p: 4 }}><UiTypography>Memuat...</UiTypography></UiBox>}");
    L.push(`        ><${name} /></Suspense>`);
    L.push('      }');
    L.push('    />');
  }
  L.push('  </>');
  L.push(');');
  L.push('');
  L.push('export const appMenu: MenuItemDef[] = [');
  for (const p of routablePages) {
    const icon = (p.icon || '').toLowerCase();
    L.push(`  { key: ${q1(p.id)}, path: ${q1(p.path)}, icon: ${q1(icon)}, titleKey: ${q1(`page.${p.id}`)} },`);
  }
  L.push('];');
  L.push('');
  return L.join('\n');
}

function bootstrapFile() {
  return [
    BANNER,
    '// Entry: deferred bootstrap (Module Federation-ready, M5). index.tsx is the',
    '// webpack entry; all app code mounts in bootstrap.tsx. Routes + menu di-wire',
    '// dari src/gen/routes.tsx (emitter M4) - tanpa menyentuh App.tsx / runtime src/gen/.',
    "import React from 'react';",
    "import { createRoot } from 'react-dom/client';",
    "import App from './App';",
    "import { appMenu, appRoutes } from './gen/routes';",
    '',
    "const container = document.getElementById('root');",
    "if (!container) throw new Error('root element #root tidak ditemukan');",
    '',
    'createRoot(container).render(',
    '  <React.StrictMode>',
    '    <App routes={appRoutes} menu={appMenu} />',
    '  </React.StrictMode>,',
    ');',
    '',
  ].join('\n');
}

