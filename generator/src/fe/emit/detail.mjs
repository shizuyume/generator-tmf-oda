// emit/detail.mjs - M4 detail emitter (todo 9).
//
// Dari FEIR page.detail -> 1 file per page (deterministik, tanpa import @mui/):
//   src/pages/<id>/Detail.tsx  - data GET retrieve (api defs), header (title/subtitle
//                                dari pageContext binding {{prefix.field}} di-resolve
//                                emit-time ke data detail dari route param :id),
//                                backButton, actions Edit/Hapus, tabs Ringkasan
//                                (description-list) + 1 table per subResource
//                                (renderColumns nested: item.policyCondition?.name).
//
// pageContext binding: FEIR bindingRefs mencatat { var: "algo.name", source:
// "pageContext", ref: "algo" }. Emitter mengubahnya menjadi accessor langsung pada
// objek detail -> TIDAK menyentuh runtime src/gen/QueryContext (namespace "algo"
// bukan namespace resmi - JANGAN dipaksa lewat resolveTemplate).
//
// Assembly MUI via barrel src/gen/ui.tsx (emit/page.mjs): UiTabs/UiTab/UiCard/UiTable/
// UiTableHead/UiTableBody/UiTableRow/UiTableCell. Emitter TIDAK meng-import @mui/.

import fs from 'node:fs';
import path from 'node:path';
import { loadAdapter } from '../../../libs/adapter.mjs';
import { endpointsFor } from './endpoints.mjs';

const BANNER = '// GENERATED by fe-gen emit - DO NOT EDIT. Re-run `fe-gen emit` instead.';
const UI_IMPORT_SLOT = '/*__DETAIL_UI_IMPORT_SLOT__*/';

/* ---------- naming helpers (sama pola emit/page.mjs) ------------------ */

const kebab = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const pascal = (s) => String(s).charAt(0).toUpperCase() + String(s).slice(1);
const pascalKebab = (s) => String(s).split('-').map(pascal).join('');
const q1 = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function resolveApiPath(template, ir) {
  const base = ir.api?.basePath ?? '';
  const out = String(template).replace(/\{\{\s*api\.basePath\s*\}\}/g, base);
  if (/\{\{/.test(out)) throw new Error(`emit/detail: binding tak dikenal di api path "${out}"`);
  return out;
}

function resourceInfo(page, ir) {
  const pathStr = resolveApiPath(page.list?.api, ir);
  const seg = pathStr.split('/').filter(Boolean).pop();
  if (!seg) throw new Error(`emit/detail: tidak dapat menentukan resource dari list.api "${page.list?.api}"`);
  // pascalKebab (bukan pascal polos): resource multi-kata dari path REST kebab-case
  // (mis. /api/retail/activity-log) HARUS jadi identifier valid (ActivityLog), bukan
  // 'Activity-log' (hyphen di nama interface/type -> SyntaxError TS). Bug nyata,
  // ditemukan lewat spec dengan resource path multi-kata pertama kali.
  return { camel: seg, kebab: kebab(seg), pascal: pascalKebab(seg) };
}

/** tone semantik -> props via adapter.resolve('button').propsMap (bukan vocab UI hardcode). */
function buttonPropsOf(adapter, tone) {
  const r = adapter.resolve('button', { tone });
  const mapped = typeof r.propsMap === 'function' ? r.propsMap({ tone }) : {};
  return Object.entries(mapped)
    .map(([k, v]) => `${k}=${q1(v)}`)
    .join(' ');
}

/* ---------- emit-time binding resolution ----------------------------- */

/** {{algo.name}} -> accessor data['name'] (pageContext ref dari bindingRefs). */
function pageContextExpr(template, page) {
  return String(template).replace(/\{\{\s*([^{}\s]+)\s*\}\}/g, (whole, raw) => {
    const dot = raw.indexOf('.');
    if (dot === -1) throw new Error(`emit/detail: pageContext var "{{${raw}}}" harus berbentuk {{prefix.field}}`);
    const prefix = raw.slice(0, dot);
    const field = raw.slice(dot + 1);
    const br = (page.bindingRefs ?? []).find((b) => b.source === 'pageContext' && b.ref === prefix);
    if (!br) throw new Error(`emit/detail: var "{{${raw}}}" pageContext "${prefix}" tidak terdaftar di bindingRefs page ${page.id}`);
    return `String((data as Record<string, unknown>)?.[${JSON.stringify(field)}] ?? '')`;
  });
}

/** Accessor field tunggal pada object detail. */
function dataField(field) {
  return `String((data as Record<string, unknown>)?.[${JSON.stringify(field)}] ?? '')`;
}

/** Accessor field tunggal pada row tabel. */
function rowField(field) {
  return `String((row as Record<string, unknown>)?.[${JSON.stringify(field)}] ?? '')`;
}

/** Accessor NESTED renderColumns {field, sub}: item.policyCondition?.name. */
function rowNested(field, sub) {
  const obj = `((row as Record<string, unknown>)?.[${JSON.stringify(field)}] as Record<string, unknown> | undefined)`;
  return `String((${obj})?.[${JSON.stringify(sub)}] ?? '')`;
}

/* ---------- block renderers (JSX string) ------------------------------ */

/** card + layout description-list: label/value pairs (mono/ link). */
function descriptionListBlock(block) {
  const fields = block.fields ?? [];
  const L = [];
  L.push('        <UiCard sx={{ p: 2 }}>');
  L.push('          <UiBox sx={{ display: \'flex\', flexDirection: \'column\', gap: 0.5 }}>');
  for (const f of fields) {
    const label = f.label ?? f.field;
    if (f.render === 'link') {
      L.push('            <UiBox sx={{ display: \'flex\', gap: 1, alignItems: \'flex-start\' }}>');
      L.push(`              <UiTypography variant="body2" sx={{ width: 170, flexShrink: 0, color: 'text.secondary' }}>{${q1(label)}}</UiTypography>`);
      L.push(`              <UiTypography variant="body2"><a href={${dataField(f.field)}} target="_blank" rel="noreferrer" style={{ color: 'inherit' }}>{${dataField(f.field)}}</a></UiTypography>`);
      L.push('            </UiBox>');
    } else {
      const mono = f.mono ? ', fontFamily: \'ui-monospace, SFMono-Regular, Menlo, monospace\', fontSize: 13' : '';
      L.push('            <UiBox sx={{ display: \'flex\', gap: 1, alignItems: \'flex-start\' }}>');
      L.push(`              <UiTypography variant="body2" sx={{ width: 170, flexShrink: 0, color: 'text.secondary' }}>{${q1(label)}}</UiTypography>`);
      L.push(`              <UiTypography variant="body2" sx={{ wordBreak: 'break-word'${mono} }}>{${dataField(f.field)}}</UiTypography>`);
      L.push('            </UiBox>');
    }
  }
  L.push('          </UiBox>');
  L.push('        </UiCard>');
  return L.join('\n');
}

/** table: field array top-level + columns plain + renderColumns nested. */
function tableBlock(block) {
  const arrayVar = block.field;
  const columns = block.columns ?? [];
  const renderColumns = block.renderColumns ?? [];
  const empty = block.emptyState?.title ?? 'Tidak ada data';
  const L = [];
  L.push('          {(() => {');
  L.push(`            const arr = (data as Record<string, unknown>)?.[${JSON.stringify(arrayVar)}];`);
  L.push('            if (!arr || !Array.isArray(arr) || arr.length === 0) {');
  L.push(`              return <UiTypography variant="body2">{${q1(empty)}}</UiTypography>;`);
  L.push('            }');
  L.push('            return (');
  L.push('              <UiTable size="small" sx={{ minWidth: 480 }}>');
  L.push('                <UiTableHead>');
  L.push('                  <UiTableRow>');
  for (const c of columns) L.push(`                    <UiTableCell>{${q1(String(c))}}</UiTableCell>`);
  for (const rc of renderColumns) L.push(`                    <UiTableCell>{${q1(String(rc.label ?? rc.field))}}</UiTableCell>`);
  L.push('                  </UiTableRow>');
  L.push('                </UiTableHead>');
  L.push('                <UiTableBody>');
  L.push('                  {(arr as unknown[]).map((row, i) => (');
  L.push('                    <UiTableRow key={i}>');
  for (const c of columns) L.push(`                      <UiTableCell>{${rowField(c)}}</UiTableCell>`);
  for (const rc of renderColumns) L.push(`                      <UiTableCell>{${rowNested(rc.field, rc.sub)}}</UiTableCell>`);
  L.push('                    </UiTableRow>');
  L.push('                  ))}');
  L.push('                </UiTableBody>');
  L.push('              </UiTable>');
  L.push('            );');
  L.push('          })()}');
  return L.join('\n');
}

/** Satu tab = kumpulan blocks (card/table). */
function tabBodyCode(tab, index, typeName) {
  const L = [];
  L.push(`function Tab${index}Body(props: { data: ${typeName} }): ReactElement {`);
  L.push('  const data = props.data;');
  L.push('  return (');
  L.push('    <UiBox sx={{ p: 1 }}>');
  for (const block of tab.blocks ?? []) {
    if (block.type === 'card' && block.layout === 'description-list') {
      L.push(descriptionListBlock(block));
    } else if (block.type === 'table') {
      L.push(tableBlock(block));
    } else {
      throw new Error(`emit/detail: block type "${block.type}" belum didukung (resmi: card/description-list | table)`);
    }
  }
  L.push('    </UiBox>');
  L.push('  );');
  L.push('}');
  return L.join('\n');
}

/* ---------- Detail.tsx ------------------------------------------------ */

function detailFile(ir, page, res, adapter) {
  const detail = page.detail;
  const listPath = page.path ?? '/';
  const hasEdit = (detail.header?.actions ?? []).some((a) => a.action === 'open-form');
  const hasDelete = (detail.header?.actions ?? []).some((a) => a.action === 'delete');
  const titleTpl = detail.header?.title ?? page.title ?? '';
  const subtitleTpl = detail.header?.subtitle ?? '';
  const titleExpr = pageContextExpr(titleTpl, page);
  const subtitleExpr = subtitleTpl ? pageContextExpr(subtitleTpl, page) : null;
  const section = (detail.sections ?? []).find((s) => s.type === 'tabs');
  const tabs = section?.tabs ?? [];
  const tabCount = tabs.length;
  const invalidSection = (detail.sections ?? []).find((s) => s.type !== 'tabs');
  if (invalidSection) throw new Error(`emit/detail: section type "${invalidSection.type}" belum didukung (resmi: tabs)`);

  const L = [];
  L.push(BANNER);
  L.push(`// Halaman detail ${page.id} (detail mode page). Data dari GET retrieve (api defs).`);
  L.push('// pageContext binding {{prefix.field}} di-resolve emit-time -> accessor data detail');
  L.push('// (route param :id) - runtime QueryContext dan src/gen/ tidak disentuh.');
  L.push(`// Tab/blocks dari FEIR detail.sections: description-list + table (renderColumns nested).`);
  L.push('');
  L.push("import { ReactElement, useCallback, useEffect, useState } from 'react';");
  L.push("import { useNavigate, useParams } from 'react-router-dom';");
  L.push('import { ArrowLeft, Pencil, Trash2 } from \'lucide-react\';');
  L.push(`import { ApiError } from '../../gen/apiClient';`);
  L.push(`import { delete${res.pascal}, get${res.pascal} } from '../../gen/api/${res.kebab}';`);
  L.push(`import type { ${res.pascal} } from '../../gen/api/${res.kebab}';`);
  L.push(UI_IMPORT_SLOT);
  if (hasEdit) L.push("import EditForm from './EditForm';");
  L.push('');
  L.push('export default function Detail(): ReactElement {');
  L.push('  const { id } = useParams();');
  L.push('  const navigate = useNavigate();');
  L.push(`  const [data, setData] = useState<${res.pascal} | null>(null);`);
  L.push('  const [loading, setLoading] = useState(true);');
  L.push('  const [error, setError] = useState<string | null>(null);');
  L.push('  const [tab, setTab] = useState(0);');
  if (hasEdit) L.push('  const [editOpen, setEditOpen] = useState(false);');
  L.push('');
  L.push('  const load = useCallback(async () => {');
  L.push('    if (id === undefined) return;');
  L.push('    setLoading(true);');
  L.push('    setError(null);');
  L.push('    try {');
  L.push(`      const detail = await get${res.pascal}(id);`);
  L.push('      setData(detail);');
  L.push('    } catch (err) {');
  L.push('      setError(err instanceof ApiError ? err.message : String(err));');
  L.push('    } finally {');
  L.push('      setLoading(false);');
  L.push('    }');
  L.push('  }, [id]);');
  L.push('');
  L.push('  useEffect(() => {');
  L.push('    void load();');
  L.push('  }, [load]);');
  L.push('');
  L.push(`  const backToList = (): void => {`);
  L.push(`    navigate(${q1(listPath)});`);
  L.push('  };');
  L.push('');
  if (hasDelete) {
    L.push(`  const handleDelete = (): void => {`);
    L.push('    if (id === undefined) return;');
    L.push("    if (window.confirm('Hapus data ini? Klik OK untuk melanjutkan.')) {");
    L.push(`      delete${res.pascal}(id)`);
    L.push('        .then(() => {');
    L.push('          backToList();');
    L.push('        })');
    L.push('        .catch((err) => {');
    L.push('          setError(err instanceof ApiError ? err.message : String(err));');
    L.push('        });');
    L.push('    }');
    L.push('  };');
    L.push('');
  }
  L.push('  if (loading) {');
  L.push('    return (<UiBox sx={{ p: 4 }}><UiTypography>Memuat...</UiTypography></UiBox>);');
  L.push('  }');
  L.push('  if (error !== null) {');
  L.push('    return (<UiBox sx={{ p: 4 }}><UiAlert severity="error">{error}</UiAlert></UiBox>);');
  L.push('  }');
  L.push('  if (data === null) {');
  L.push('    return (<UiBox sx={{ p: 4 }}><UiTypography>Data tidak ditemukan</UiTypography></UiBox>);');
  L.push('  }');
  L.push('');
  L.push('  return (');
  L.push('    <UiBox sx={{ display: \'flex\', flexDirection: \'column\', gap: 2, minHeight: \'60vh\' }}>');
  L.push('      <UiBox sx={{ display: \'flex\', alignItems: \'flex-start\', gap: 1, flexWrap: \'wrap\' }}>');
  L.push(`        <UiIconButton size="small" title="Kembali" aria-label="Kembali" onClick={backToList}><ArrowLeft size={18} /></UiIconButton>`);
  L.push('        <UiBox sx={{ flexGrow: 1, minWidth: 240 }}>');
  L.push(`          <UiTypography variant="h5">{${titleExpr}}</UiTypography>`);
  if (subtitleExpr) L.push(`          <UiTypography variant="body2" sx={{ color: 'text.secondary' }}>{${subtitleExpr}}</UiTypography>`);
  L.push('        </UiBox>');
  const actions = detail.header?.actions ?? [];
  if (actions.length) {
    L.push('        <UiBox sx={{ display: \'flex\', gap: 1 }}>');
    for (const a of actions) {
      if (a.action === 'open-form') {
        const btnProps = buttonPropsOf(adapter, a.variant ?? 'primary');
        L.push(`          <UiButton ${btnProps} startIcon={<Pencil size={16} />} onClick={() => setEditOpen(true)}>{${q1(a.label)}}</UiButton>`);
      } else if (a.action === 'delete') {
        const btnProps = buttonPropsOf(adapter, a.variant ?? 'danger');
        L.push(`          <UiButton ${btnProps} startIcon={<Trash2 size={16} />} onClick={handleDelete}>{${q1(a.label)}}</UiButton>`);
      } else {
        throw new Error(`emit/detail: header action "${a.action}" tak dikenal (resmi: open-form | delete)`);
      }
    }
    L.push('        </UiBox>');
  }
  L.push('      </UiBox>');
  L.push('      <UiBox sx={{ width: \'100%\' }}>');
  L.push('        <UiTabs value={tab} onChange={(_e: unknown, v: number) => setTab(v)}>');
  for (const t of tabs) L.push(`          <UiTab label={${q1(t.label)}} />`);
  L.push('        </UiTabs>');
  L.push('      </UiBox>');
  L.push('      <UiBox sx={{ width: \'100%\' }}>');
  L.push('        {(() => {');
  L.push('          switch (tab) {');
  tabs.forEach((t, i) => {
    L.push(`            case ${i}: return <Tab${i}Body data={data} />;`);
  });
  L.push('            default: return <Tab0Body data={data} />;');
  L.push('          }');
  L.push('        })()}');
  L.push('      </UiBox>');
  if (hasEdit) {
    L.push('      {editOpen && id !== undefined ? <EditForm open={editOpen} id={id} onClose={() => setEditOpen(false)} onSaved={() => void load()} /> : null}');
  }
  L.push('    </UiBox>');
  L.push('  );');
  L.push('}');
  L.push('');

  // tab body components di-emit SETELAH komponen utama (named + default export).
  tabs.forEach((t, i) => {
    L.push(tabBodyCode(t, i, res.pascal));
    L.push('');
  });

  // Sama pola dengan emit/page.mjs (CRUD_IMPORT_SLOT/UI_IMPORT_SLOT, F0/F8): saring barrel
  // Ui* dari TEKS body yang sudah jadi (termasuk semua Tab*Body), bukan dari kondisi yang
  // menyusunnya - dulu diimpor tanpa syarat, jadi detail page dengan blok bukan-tabel
  // (mis. hanya description-list, tanpa satu pun blok `table`) membawa UiTable/UiTableHead/
  // UiTableBody/UiTableRow/UiTableCell yang tak terpakai (eslint no-unused-vars).
  const uiSlot = L.indexOf(UI_IMPORT_SLOT);
  const bodyText = L.filter((_, i) => i !== uiSlot).join('\n');
  const uiCandidates = ['UiAlert', 'UiBox', 'UiButton', 'UiCard', 'UiIconButton', 'UiTable', 'UiTableBody', 'UiTableCell', 'UiTableHead', 'UiTableRow', 'UiTabs', 'UiTab', 'UiTypography'];
  const usedUi = uiCandidates.filter((name) => new RegExp(`\\b${name}\\b`).test(bodyText));
  L[uiSlot] = `import { ${usedUi.join(', ')} } from '../../gen/ui';`;

  

  return L.join('\n');
}

/* ---------- emitDetails ------------------------------------------------ */

/**
 * Emit detail pages untuk setiap page FEIR yang punya detail.
 * @returns {{ written: string[], summary: string }}
 */
export function emitDetails(feir, appDir) {
  if (feir.output?.mfe?.federationTemplate === 'common-remote') {
    // mcs-common owns detail emission entirely (emit/mcs-common/pages.mjs's *DetailPage,
    // incl. the Card/Table viewToggle) - see emit/mfe.mjs's matching guard.
    return { written: [], summary: 'detail: federationTemplate=common-remote - delegasi ke emit/mcs-common (detail.mjs dilewati)' };
  }
  const written = [];
  const adapter = loadAdapter(feir.ui?.library ?? 'mui');
  const write = (rel, content) => {
    if (content.includes('\uFFFD')) {
      throw new Error(`emit/detail: U+FFFD ditemukan di "${rel}" (mojibake guard) - berhenti`);
    }
    const abs = path.join(appDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  let detailPages = 0;
  for (const page of feir.pages ?? []) {
    if (!page.detail) continue;
    const eps = endpointsFor(feir, page);
    if (!eps.retrieve) {
      throw new Error(`emit/detail: page ${page.id} punya detail tapi FEIR tidak punya endpoint retrieve (no invented endpoints)`);
    }
    if (!page.detail.path) throw new Error(`emit/detail: page ${page.id} detail tanpa path`);
const res = resourceInfo(page, feir);
    write(`src/pages/${page.id}/Detail.tsx`, detailFile(feir, page, res, adapter));
    detailPages += 1;
  }

  return {
    written: written.sort(),
    summary: `${detailPages} detail page(s) -> src/pages/<id>/Detail.tsx (route :id + barrel di emit/page.mjs)`,
  };
}
