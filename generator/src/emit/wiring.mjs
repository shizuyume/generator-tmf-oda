import fs from 'node:fs';
import path from 'node:path';
import { pascal, kebab, snake } from '../ir/naming.mjs';
import { renderSeedRunner } from './seed.mjs';
import {
  LATEST_ORDER_COLUMN,
  LATEST_ORDER_DIRECTION,
  LATEST_TAKE,
  PLACEHOLDER_SUBSCRIPTION,
  HUB_PATH_SEGMENT,
} from './behaviour.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';
const MANIFEST = '.tmfgen-manifest.json';

/**
 * Service-level wiring, regenerated from the MANIFEST rather than from a single IR.
 *
 * A service can host several TMF components (the geographic case puts TMF673/674/675
 * in one service), and each brings its own base path, event exchange, event enum, hub
 * route and listener routes. Regenerating from one component at a time silently
 * dropped the others - emitting TMF674 wiped TMF673 out of app.module.ts and left its
 * controllers referencing a TMF674_BASE_PATH that was never written.
 *
 * So every shared file here is derived from the union of components:
 *   tmf.constants.ts      one base path + exchange per component
 *   entities.ts           every component's entities, infra entities last
 *   app.module.ts         every component's resource modules
 *   event-types.ts        one enum per component
 *   {slug}-subscription.controller.ts   hub, per component (own base path)
 *   {slug}-listener.controller.ts       listener stubs, per component
 *   subscription.module.ts / listener.module.ts   register all of the above
 */

export function manifestPath(backendDir) {
  return path.join(backendDir, MANIFEST);
}

export function readManifest(backendDir) {
  const p = manifestPath(backendDir);
  if (!fs.existsSync(p)) return { generatorVersion: '0.1.0', components: {} };
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

export function writeManifest(backendDir, manifest) {
  fs.writeFileSync(manifestPath(backendDir), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
}

/** Component entry derived from an IR; `resources`/`entities` fill in during emit. */
export function componentEntry(ir, existing = {}) {
  const m = ir.meta;
  return {
    tmfNumber: m.tmfNumber,
    specTitle: m.specTitle,
    specVersion: m.specVersion,
    slug: kebab(m.eventExchange.replace(/\.events$/, '')),
    basePath: m.basePath,
    basePathConstant: m.basePathConstant,
    eventExchange: m.eventExchange,
    eventExchangeConstant: m.eventExchangeConstant,
    eventTypeEnum: m.eventTypeEnum,
    resources: existing.resources ?? [],
    seeds: existing.seeds ?? [],
    entities: existing.entities ?? [],
    events: existing.events ?? [],
    listeners: existing.listeners ?? [],
  };
}

/**
 * Every component the service hosts, in a stable order. Exported because the
 * spec emitters must see the same union these shared files are built from: a
 * suite generated from one component's IR describes one component and silently
 * ignores the rest of the service it is supposed to test.
 */
export const orderedComponents = manifest =>
  Object.values(manifest.components).sort((a, b) => a.tmfNumber.localeCompare(b.tmfNumber));

const ordered = orderedComponents;

/* ── shared files ────────────────────────────────────────────────────── */

function tmfConstants(components) {
  const lines = [BANNER];
  for (const c of components) {
    lines.push(`// TMF${c.tmfNumber} ${c.specTitle}`);
    lines.push(`export const ${c.basePathConstant} = '${c.basePath}';`);
    lines.push(`export const ${c.eventExchangeConstant} = '${c.eventExchange}';`);
  }
  lines.push('');
  return lines.join('\n');
}

function entitiesBarrel(components) {
  const all = components.flatMap(c => c.entities);
  const seen = new Set();
  const unique = all.filter(e => (seen.has(e.className) ? false : seen.add(e.className)));
  return [
    BANNER,
    ...unique.map(e => `import { ${e.className} } from './${e.importPath}';`),
    "import { EventSubscription } from './subscription/entities/event-subscription.entity';",
    "import { EventLog } from './event/entities/event-log.entity';",
    '',
    'export const entities = [',
    ...unique.map(e => `  ${e.className},`),
    '  EventSubscription,',
    '  EventLog,',
    '];',
    '',
  ].join('\n');
}

function eventTypes(components) {
  const lines = [BANNER];
  for (const c of components) {
    lines.push(`/** TMF${c.tmfNumber} - event names come from the spec's /listener/* paths. */`);
    lines.push(`export enum ${c.eventTypeEnum} {`);
    if (c.events.length) {
      for (const e of c.events) lines.push(`  ${e.enumMember} = '${e.eventName}',`);
    } else {
      lines.push('  // the spec declares no notification events for this component');
    }
    lines.push('}');
    lines.push('');
  }
  return lines.join('\n');
}

function subscriptionController(c) {
  const cls = `${pascal(c.slug)}SubscriptionController`;
  return {
    file: `src/subscription/${c.slug}-subscription.controller.ts`,
    className: cls,
    importPath: `./${c.slug}-subscription.controller`,
    text: `${BANNER}
import {
  Controller,
  Get,
  Post,
  Delete,
  Body,
  Param,
  Query,
  HttpCode,
  HttpStatus,
  UseInterceptors,
  UseGuards,
  Res,
} from '@nestjs/common';
import { Response } from 'express';
import { ApiTags } from '@nestjs/swagger';
import { ApiKeyGuard } from '../common/guards/api-key.guard';
import { PaginationInterceptor } from '../common/interceptors/pagination.interceptor';
import { ${c.basePathConstant} } from '../common/constants/tmf.constants';
import { SubscriptionService } from './subscription.service';
import { CreateSubscriptionDto } from './dto/create-subscription.dto';

// GET /hub is a house convention: the spec declares only POST and DELETE.
@ApiTags('hub')
@UseGuards(ApiKeyGuard)
@UseInterceptors(PaginationInterceptor)
@Controller(\`\${${c.basePathConstant}}/${HUB_PATH_SEGMENT}\`)
export class ${cls} {
  constructor(private readonly subscriptionService: SubscriptionService) {}

  @Get()
  async findAll(
    @Query('offset') offset?: string,
    @Query('limit') limit?: string,
  ) {
    return this.subscriptionService.findAll(
      Number(offset) || 0,
      Number(limit) || 20,
    );
  }

  @Post()
  @HttpCode(HttpStatus.CREATED)
  async create(
    @Body() dto: CreateSubscriptionDto,
    @Res({ passthrough: true }) res: Response,
  ) {
    const result = await this.subscriptionService.create(dto);
    const href = \`\${${c.basePathConstant}}/${HUB_PATH_SEGMENT}/\${result.id}\`;
    res.location(href);
    return { ...result, href };
  }

  @Delete(':id')
  @HttpCode(HttpStatus.NO_CONTENT)
  async remove(@Param('id') id: string): Promise<void> {
    await this.subscriptionService.remove(id);
  }
}
`,
  };
}

function listenerController(c) {
  const cls = `${pascal(c.slug)}ListenerController`;
  const handlers = c.listeners.map(l => `
  @Post('${l.eventName}')
  @HttpCode(HttpStatus.CREATED)
  async handle${pascal(l.eventName)}(@Body() body: any) {
    this.logger.log('Received ${l.eventName}');
    return this.findSubscription(body);
  }`).join('\n');

  return {
    file: `src/listener/${c.slug}-listener.controller.ts`,
    className: cls,
    importPath: `./${c.slug}-listener.controller`,
    text: `${BANNER}
import {
  Controller,
  Post,
  Body,
  Logger,
  HttpCode,
  HttpStatus,
} from '@nestjs/common';
import { ApiTags } from '@nestjs/swagger';
import { Repository } from 'typeorm';
import { InjectRepository } from '@nestjs/typeorm';
import { ${c.basePathConstant} } from '../common/constants/tmf.constants';
import { EventSubscription } from '../subscription/entities/event-subscription.entity';

// Publish-only architecture: these endpoints are stubs that log and echo, matching
// the reference. Nothing is consumed here.
@ApiTags('listener')
@Controller(\`\${${c.basePathConstant}}/listener\`)
export class ${cls} {
  private readonly logger = new Logger(${cls}.name);

  constructor(
    @InjectRepository(EventSubscription)
    private readonly subscriptionRepository: Repository<EventSubscription>,
  ) {}

  private async findSubscription(body: any): Promise<EventSubscription> {
    if (body?.subscriptionId) {
      const sub = await this.subscriptionRepository.findOne({
        where: { id: body.subscriptionId },
      });
      if (sub) return sub;
    }
    const [latest] = await this.subscriptionRepository.find({
      order: { ${LATEST_ORDER_COLUMN}: '${LATEST_ORDER_DIRECTION}' },
      take: ${LATEST_TAKE},
    });
    return (
      latest ||
      ({
        id: '${PLACEHOLDER_SUBSCRIPTION.id}',
        callback: '${PLACEHOLDER_SUBSCRIPTION.callback}',
        createdDate: new Date(),
      } as unknown as EventSubscription)
    );
  }
${handlers}
}
`,
  };
}

function moduleFile({ name, controllers, providers = [], extraImports = [] }) {
  return [
    BANNER,
    "import { Module } from '@nestjs/common';",
    "import { TypeOrmModule } from '@nestjs/typeorm';",
    ...extraImports,
    ...controllers.map(c => `import { ${c.className} } from '${c.importPath}';`),
    ...providers.map(p => `import { ${p.className} } from '${p.importPath}';`),
    '',
    '@Module({',
    '  imports: [TypeOrmModule.forFeature([EventSubscription])],',
    `  controllers: [${controllers.map(c => c.className).join(', ')}],`,
    ...(providers.length ? [`  providers: [${providers.map(p => p.className).join(', ')}],`] : []),
    '})',
    `export class ${name} {}`,
    '',
  ].join('\n');
}

function appModule(components, databaseName) {
  const modules = components.flatMap(c => c.resources.map(r => ({
    className: r.moduleClass,
    importPath: r.moduleImportPath,
  })));
  const imports = modules.map(m => `import { ${m.className} } from './${m.importPath}';`);
  const entries = modules.map(m => `    ${m.className},`);
  return `${BANNER}
import { Module } from '@nestjs/common';
import { ConfigModule, ConfigService } from '@nestjs/config';
import { TypeOrmModule } from '@nestjs/typeorm';
import { EventEmitterModule } from '@nestjs/event-emitter';
import { entities } from './entities';
${imports.join('\n')}${imports.length ? '\n' : ''}import { EventModule } from './event/event.module';
import { SubscriptionModule } from './subscription/subscription.module';
import { ListenerModule } from './listener/listener.module';

@Module({
  imports: [
    ConfigModule.forRoot(),
    EventEmitterModule.forRoot(),
    TypeOrmModule.forRootAsync({
      imports: [ConfigModule],
      inject: [ConfigService],
      useFactory: (configService: ConfigService) => {
        const dbType = configService.get<string>('DATABASE_TYPE') || 'sqlite';
        if (dbType === 'postgres') {
          return {
            type: 'postgres',
            host: configService.get<string>('DATABASE_HOST') || 'localhost',
            port: configService.get<number>('DATABASE_PORT') || 5432,
            username:
              configService.get<string>('DATABASE_USERNAME') || 'postgres',
            password:
              configService.get<string>('DATABASE_PASSWORD') || 'postgres',
            database:
              configService.get<string>('DATABASE_NAME') || '${databaseName}',
            entities,
            synchronize:
              configService.get<string>('DATABASE_SYNCHRONIZE') === 'true',
            logging: configService.get<string>('DATABASE_LOGGING') === 'true',
          };
        }
        return {
          type: 'sqlite',
          database: configService.get<string>('DATABASE_PATH') || './dev.db',
          entities,
          synchronize:
            configService.get<string>('DATABASE_SYNCHRONIZE') !== 'false',
          logging: configService.get<string>('DATABASE_LOGGING') === 'true',
        };
      },
    }),
${entries.join('\n')}${entries.length ? '\n' : ''}    EventModule,
    SubscriptionModule,
    ListenerModule,
  ],
})
export class AppModule {}
`;
}

/**
 * Regenerate every shared file from the manifest.
 * @returns {string[]} files written, relative to backendDir
 */
export function writeWiring(backendDir, manifest, { databaseName }) {
  const components = ordered(manifest);
  const written = [];
  const put = (rel, content) => {
    const abs = path.join(backendDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  put('src/common/constants/tmf.constants.ts', tmfConstants(components));
  put('src/entities.ts', entitiesBarrel(components));
  put('src/event/event-types.ts', eventTypes(components));
  put('src/app.module.ts', appModule(components, databaseName));

  const subs = components.map(subscriptionController);
  const listeners = components.map(listenerController);
  for (const s of subs) put(s.file, s.text);
  for (const l of listeners) put(l.file, l.text);

  // one seed runner for the whole service, covering every component it hosts
  const seedEntries = components.flatMap(c => c.seeds ?? []);
  const runner = renderSeedRunner(seedEntries);
  put(`src/${runner.fileName}`, runner.text);

  put('src/subscription/subscription.module.ts', moduleFile({
    name: 'SubscriptionModule',
    controllers: subs,
    providers: [{ className: 'SubscriptionService', importPath: './subscription.service' }],
    extraImports: ["import { EventSubscription } from './entities/event-subscription.entity';"],
  }));
  put('src/listener/listener.module.ts', moduleFile({
    name: 'ListenerModule',
    controllers: listeners,
    extraImports: ["import { EventSubscription } from '../subscription/entities/event-subscription.entity';"],
  }));

  return written;
}
