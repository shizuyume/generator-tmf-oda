import { camel, kebab } from '../../ir/naming.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';
const PRINT_WIDTH = 80;

/**
 * test/hooks.spec.ts - one suite per resource's hook module.
 *
 * `*.hooks.ts` is written ONCE if absent and never overwritten (see
 * emit/index.mjs); its own banner says "NOT managed by tmfgen" and the file
 * invites the user to put domain logic in it. So this suite may assert only
 * what is true of EVERY valid implementation: the three exports exist, are
 * callable, and calling them does not throw synchronously.
 *
 * It deliberately does NOT assert return values. An earlier version required
 * beforeUpdate and afterFindOne to resolve to undefined, which is true only of
 * the generated stub: the moment a user returned a modified payload - the whole
 * point of the seam - a file stamped "DO NOT EDIT" went red with no way to fix
 * it. (beforeCreate's assertion was wrapped in `if (result !== undefined)` and
 * so asserted nothing at all.) A generated service whose hooks module fails to
 * export beforeCreate is a real bug, and that is still caught here.
 *
 * Import path is rebased from `renderHooks`'s own write site (emit/index.mjs):
 * `src/${dir}/${kebab(resource.name)}.hooks.ts`. The hooks file name comes from
 * kebab(resource.name), NOT naming.moduleFileBase - the two diverge whenever
 * moduleNaming remaps a scaffold-owned dir (event/subscription/listener/common)
 * to `tmf-<base>`: dir becomes `tmf-<base>` but the hooks file stays `<base>.hooks.ts`.
 */
/** `['label', mod(alias)],`, broken the way Prettier breaks it when too wide. */
function moduleEntryLines(label, alias) {
  const single = `  ['${label}', mod(${alias})],`;
  if (single.length <= PRINT_WIDTH) return [single];
  return ['  [', `    '${label}',`, `    mod(${alias}),`, '  ],'];
}

export function emitHooksSpec({ resources }) {
  if (!resources.length) return null;

  // Two hosted components can name a resource the same way, and then they share
  // one directory and one hooks file. Import it once.
  const seen = new Set();
  const mods = [];
  for (const r of resources) {
    const modPath = `../src/${r.dir}/${kebab(r.resource)}.hooks`;
    if (seen.has(modPath)) continue;
    seen.add(modPath);
    mods.push({ alias: `${camel(r.resource)}Hooks`, path: modPath, label: camel(r.resource) });
  }

  const lines = [
    BANNER,
    '/**',
    ' * The per-resource hook modules are the domain seam the generated services call',
    ' * at fixed points. They are created once and then owned by whoever implements',
    ' * the component, so the only contract this suite may assert is the one every',
    ' * valid implementation keeps: each hook is exported, is callable, and calling',
    ' * it does not throw. Return values are deliberately NOT asserted - a hook that',
    ' * enriches its payload is the seam working, not a regression.',
    ' */',
    ...mods.map(m => `import * as ${m.alias} from '${m.path}';`),
    '',
    'type HookFn = (...args: any[]) => unknown;',
    'type Hooks = Record<string, HookFn>;',
    '',
    'const mod = (m: unknown) => m as Hooks;',
    '',
    'const MODULES: [string, Hooks][] = [',
    ...mods.flatMap(m => moduleEntryLines(m.label, m.alias)),
    '];',
    '',
    '/** One representative call per hook, with the arguments the service passes. */',
    'const CALL: Record<string, (h: Hooks) => unknown> = {',
    "  beforeCreate: (h) => h.beforeCreate({ name: 'A' }),",
    "  beforeUpdate: (h) => h.beforeUpdate('id-1', { name: 'A' }),",
    "  afterFindOne: (h) => h.afterFindOne({ id: 'id-1' }, {}),",
    '};',
    '',
    'const HOOKS = Object.keys(CALL);',
    '',
    "describe.each(MODULES)('%s hooks', (_name, hooks) => {",
    "  it.each(HOOKS)('exports %s and calling it does not throw', (name) => {",
    "    expect(typeof hooks[name]).toBe('function');",
    '    let returned: unknown;',
    '    expect(() => {',
    '      returned = CALL[name](hooks);',
    '    }).not.toThrow();',
    '    // An implementation is free to reject - a validation error, say. That is',
    "    // not this suite's business, but an unhandled rejection would fail it.",
    '    void Promise.resolve(returned).catch(() => undefined);',
    '  });',
    '});',
    '',
  ];
  return { rel: 'test/hooks.spec.ts', text: lines.join('\n') };
}
