/**
 * test/<dir>/<resource>.service.spec.ts - ONE file per resource, exercising the
 * generated service and controller against mocked repositories.
 *
 * This is the only spec emitter that returns an ARRAY: the other five describe
 * the whole service (one seed runner, one hooks barrel, ...) and so must be
 * built from the manifest UNION. A per-resource file describes exactly ONE
 * resource, so it is built from the IR being emitted (`ctx.plans`) instead.
 * That is not the multi-component bug plan 2 fixed: emitting component A
 * rewrites A's resources' spec files and leaves B's - written when B was
 * emitted - untouched and still correct. Per-resource files are inherently
 * per-component and idempotent.
 *
 * A manifest resource entry could not drive this: it carries only
 * `className, dir, importPath, moduleClass, moduleImportPath, pathSegment,
 * resource` - no columns, no relations, no refs - and the fixture needs all
 * three.
 *
 * WHERE EACH FIXTURE PART COMES FROM. None of it is copied from the reference
 * service's literals, which are TMF642's; each is read back off the renderer in
 * emit/service.mjs that writes the code being described, so a TMF-shaped
 * Swagger spec that is not a TM Forum component produces the equivalent.
 *
 *   <R>Service / <R>Controller import
 *       `src/<dir>/<kebab(resource.name)>.service|controller`, the paths
 *       emit/index.mjs writes them to, rebased to `../../src/...` because the
 *       spec sits two levels down under test/.
 *   <C>EventType import
 *       `../event/event-types` in the service (renderService's import list,
 *       host.eventTypeStyle === 'enum'), named ir.meta.eventTypeEnum. The
 *       barrel declares one enum per hosted component and exports it even when
 *       the spec declared no notification events, so the import always resolves.
 *   entity class imports
 *       one per DISTINCT resolved class name across plan.entities - the same
 *       `uniqueClasses` de-duplication renderService does - each from the
 *       directory the class was actually written into (a shared class lives
 *       under the first resource that needed it, hence entityDirOf).
 *   COLLECTIONS
 *       the root entity's `one-to-many` relations, by property name: exactly
 *       renderService's `collectionRelations`.
 *   HREF
 *       renderMapper writes the root href as `/<BASE_PATH>/<segment>/<e.id>`,
 *       with segment = nested.hrefSegment when --nested-routes applies and
 *       resource.pathSegment otherwise. The id is the fixture root's, `res-1`.
 *   HREF_SEGMENT
 *       an OWNED child's mapper writes
 *       `/<BASE>/<pathSegment>/<rootId>/<entity.ownerField>/<e.refId ?? e.id>`,
 *       so the segment is the TARGET entity's ownerField - not the collection's
 *       own property name. When two collections share one entity class only ONE
 *       mapper is emitted for it, and renderService's `new Map(...)` keeps the
 *       LAST entity carrying that class name, so both collections get that one
 *       entity's ownerField. A refLike child gets no href and is omitted.
 *   ROW_AT_TYPE (row()'s atType)
 *       the collection's target entity class name, which is what that class's
 *       own `atType` column holds on the wire.
 *   entity()'s scalars
 *       the root entity's non-housekeeping columns: the primary key as `res-1`
 *       (so it agrees with HREF), `atType` as the create path's default
 *       (defaultAtType(resource.name)), every other column as `res-<name>`.
 *   ROUTE_PATH
 *       renderController writes `@Controller(`${<BASE>_BASE_PATH}/<segment>`)`,
 *       so PATH_METADATA holds `<meta.basePath>/<segment>` with segment =
 *       nested.routeSegment (`topic/:topicId/event`) when --nested-routes applies
 *       and resource.pathSegment otherwise. This is the ROUTE segment, not the
 *       href segment HREF uses - the two differ for a nested resource.
 *   ID / FIELD
 *       the fixture root's primary key value (`res-1`, agreeing with HREF) and
 *       the root's first non-housekeeping, non-primary, non-atType column - the
 *       scalar the controller's write bodies and field selection move. A root
 *       with no such column falls back to its own primary key name.
 *   CREATE_BODY / UPDATE_BODY / LIST_QUERY
 *       payloads over FIELD alone: the service is a double, so only the
 *       pass-through is under test, not the DTO's shape.
 *   PARENTS
 *       nested.params, each as `<param>-1`. renderController takes them as
 *       leading @Param()s and renderService receives them merged into the
 *       create/list payload or as a trailing scope argument.
 *   Create<R>Dto / Update<R>Dto import
 *       the same `./dto` barrel renderController imports its @Body() types from,
 *       rebased to `../../src/<dir>/dto`; imported only for the operations that
 *       actually declare a write body.
 */

/**
 * Columns that belong to US (audit / soft delete) rather than to the spec.
 * Narrower than service.mjs's isHousekeeping by design: that one also falls
 * back to AUDIT_AND_SOFT_DELETE by NAME for plans built before the flag
 * existed, which would drop a spec-declared `lastUpdate` from the fixture. Every
 * plan reaching this emitter is built in-process and carries the flag.
 */
function isHousekeeping(c) {
  if (c.housekeeping) return true;
  return !!(c.createDateColumn || c.updateDateColumn || c.deleteDateColumn);
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** A single-quoted TS string literal. */
function q(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** An object key, quoted only when it is not a plain identifier. */
function key(name) {
  return IDENT.test(name) ? name : q(name);
}

/**
 * One `key: value,` of an object literal. Prettier moves a value that does not
 * fit onto its own indented line rather than letting the entry overflow - and
 * a TMF class name used as a value reaches that easily
 * (`alternateGeographicAddress: 'GeographicAddressValidationAlternateGeographicAddress'`).
 */
function propLine(k, value, indent, pad = 0) {
  const single = `${indent}${key(k)}: ${value},`;
  if (single.length + pad <= PRINT_WIDTH) return [single];
  return [`${indent}${key(k)}:`, `${indent}  ${value},`];
}

/**
 * `const NAME: TYPE = { a: 'b', ... };` on one line when it fits in Prettier's
 * print width, otherwise one entry per line with a trailing comma - which is
 * what `prettier --write` produces under the service's own .prettierrc
 * (singleQuote, trailingComma: all).
 */
function objectConst(name, type, entries, pad = 0) {
  const decl = `const ${name}${type ? `: ${type}` : ''} = `;
  if (!entries.length) return [`${decl}{};`];
  const inline = `${decl}{ ${entries.map(([k, v]) => `${key(k)}: ${v}`).join(', ')} };`;
  if (inline.length + pad <= PRINT_WIDTH) return [inline];
  return [`${decl}{`, ...entries.flatMap(([k, v]) => propLine(k, v, '  ', pad)), '};'];
}

/** Re-indents a block a helper produced at column 0. */
function indented(prefix, lines) {
  return lines.map(l => (l ? `${prefix}${l}` : l));
}

/**
 * `const NAME = '...';`. Prettier cannot split a string literal, but it DOES
 * move one that overflows onto its own indented line - which a long base path
 * plus a long path segment reaches easily (TMF736's is 88 characters).
 */
function stringConst(name, value) {
  const inline = `const ${name} = ${q(value)};`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [`const ${name} =`, `  ${q(value)};`];
}

/**
 * `name: [row('name', 0)],` inside entity(). Prettier breaks the ARRAY, not the
 * assignment, when this one overflows.
 */
function collectionProp(prop, indent) {
  const single = `${indent}${key(prop)}: [row(${q(prop)}, 0)],`;
  if (single.length <= PRINT_WIDTH) return [single];
  return [
    `${indent}${key(prop)}: [`,
    `${indent}  row(${q(prop)}, 0),`,
    `${indent}],`,
  ];
}

/** `const NAME = ['a', 'b'] as const;`, broken the way Prettier breaks it. */
function tupleConst(name, values) {
  const inline = `const ${name} = [${values.map(q).join(', ')}] as const;`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [`const ${name} = [`, ...values.map(v => `  ${q(v)},`), '] as const;'];
}

/** `for (const E of [A, B]) {`, broken the way Prettier breaks it. */
function forOfClasses(classNames, indent) {
  const inline = `${indent}for (const E of [${classNames.join(', ')}]) {`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [
    `${indent}for (const E of [`,
    ...classNames.map(cn => `${indent}  ${cn},`),
    `${indent}]) {`,
  ];
}

/**
 * `head(a, b)tail` on one line when it fits, otherwise one argument per line -
 * which is how Prettier breaks a call whose arguments are all plain references.
 */
function callLines(indent, head, args, tail = ';') {
  const inline = `${indent}${head}(${args.join(', ')})${tail}`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [
    `${indent}${head}(`,
    ...args.map(a => `${indent}  ${a},`),
    `${indent})${tail}`,
  ];
}

/**
 * `expect(x).toEqual([A]);`. The only argument is an array literal, so Prettier
 * hugs it and breaks the ARRAY rather than the call.
 */
function expectEqualArray(indent, subject, items) {
  const inline = `${indent}expect(${subject}).toEqual([${items.join(', ')}]);`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [
    `${indent}expect(${subject}).toEqual([`,
    ...items.map(i => `${indent}  ${i},`),
    `${indent}]);`,
  ];
}

/**
 * `name: jest.fn(async () => ({ a: 'b' })),` inside the service double. The
 * returned object literal is the arrow's only expression, so Prettier hugs it
 * and breaks the OBJECT.
 */
function jestFnEntry(indent, name, entries) {
  const body = entries.map(([k, v]) => `${key(k)}: ${v}`).join(', ');
  const inline = `${indent}${name}: jest.fn(async () => ({ ${body} })),`;
  if (inline.length <= PRINT_WIDTH) return [inline];
  return [
    `${indent}${name}: jest.fn(async () => ({`,
    ...entries.flatMap(([k, v]) => propLine(k, v, `${indent}  `)),
    `${indent}})),`,
  ];
}

/**
 * `import { A, B } from 'x';`. Prettier breaks an import whose SPECIFIER LIST
 * overflows - two long DTO class names from one `./dto` barrel reach that - but
 * leaves a single-specifier import alone however long the module path is, which
 * is why the entity imports above stay on one line.
 */
function importLine(names, from) {
  const inline = `import { ${names.join(', ')} } from ${q(from)};`;
  if (names.length < 2 || inline.length <= PRINT_WIDTH) return [inline];
  return ['import {', ...names.map(n => `  ${n},`), `} from ${q(from)};`];
}

