/**
 * The service describe - `create` only for now; the other operations follow in
 * their own slices.
 *
 * WHAT EACH `it()` IS GATED ON, and why. emit/service.mjs emits `create`
 * unconditionally (the seed runner calls it even for a read-only resource), but
 * the code INSIDE it varies with the resource, so each assertion is gated on the
 * shape that produces the line it describes:
 *
 *   scalars / href      always. `create` exists for every resource.
 *   create event        resource.notificationEvents carries eventKind 'Create',
 *                       which is the only thing that makes renderService emit an
 *                       emitCall at all.
 *   client id / @type   always: `if (!entity.atType) entity.atType = '...'` is
 *                       unconditional. The "keeps a SUPPLIED @type" half needs
 *                       the root to actually carry an atType column, because
 *                       only then does the builder read `input['@type']`.
 *   soft-delete stamps  root.softDelete. entityPlan sets it on every root, but
 *                       the gate says what the assertion depends on.
 *   single refs first   the ROOT's `many-to-one-ref` relations - NOT
 *                       resource.resourceRefs. Those are `many-to-one-resource`
 *                       (sibling resources with their own service) and are
 *                       joined, not pushed onto `pending`. What drives the
 *                       refSave-before-save ordering is renderBuilder's
 *                       `pending.push` on a `kind: 'ref'` entity, and only a
 *                       many-to-one-ref targets one.
 *   nested row first    a collection whose TARGET carries a many-to-one-ref -
 *                       again the pending queue, one level down (the reference's
 *                       RelatedPlace -> Place). A collection that merely owns
 *                       another collection pends nothing and would assert
 *                       nothing.
 *   sortOrder numbering at least one collection: renderBuilder's
 *                       `Object.assign(..., { sortOrder: __i })`.
 *   empty payload       refs or collections; there is nothing to be absent
 *                       otherwise.
 *   beforeCreate        always: `hooks.beforeCreate(dto) ?? dto` is
 *                       unconditional.
 *
 * THE HOOK ASSERTION IS ABOUT THE CALL. `*.hooks.ts` is user-owned and carries
 * "NOT managed by tmfgen"; a generated spec that asserted what it RETURNS goes
 * red the moment someone implements it. So the hook is SPIED and given a
 * payload, and what is under test is that `create` builds from the value it got
 * back - never what the shipped stub happens to return.
 *
 * Every value the generated service also knows is interpolated from
 * emit/behaviour.mjs: the `@type` default, the soft-delete column names, the
 * sortOrder of a first row. A literal here would let the suite drift into
 * asserting a regression as correct, which is the whole reason that module
 * exists.
 */
function serviceBlock({ resource, plan, root, meta, host, resolve, src, fileBase }) {
  const svcClass = `${resource.name}Service`;
  const pkCol = root.columns.find(c => c.primary);
  const pk = pkCol ? pkCol.name : 'id';
  const pkKey = IDENT.test(pk) ? `.${pk}` : `[${q(pk)}]`;

  const entityByKey = new Map(plan.entities.map(e => [e.key, e]));
  const refIdColOf = e => (e?.columns ?? []).find(c => c.sourceProp === 'id')?.name ?? null;

  // one repository constructor parameter per DISTINCT entity class, the root's
  // first (renderService names index 0 `repository` and aliases the root repo
  // onto it), then dataSource, then the event emitter.
  const repoCount = new Set(
    plan.entities.map(e => resolve(e.key)?.className).filter(Boolean),
  ).size;

  const hasAtType = root.columns.some(c => c.name === 'atType');

  // The payload keys renderBuilder reads (responseKey: '@type', '@baseType', ...)
  // mapped to the columns they land in. `atType` is excluded - it has its own
  // default, asserted separately - as is a server-managed `version`.
  const scalars = [];
  for (const c of root.columns) {
    if (isHousekeeping(c) || c.primary || c.isVersion) continue;
    if (c.name === 'atType') continue;
    scalars.push([c.sourceProp || c.expose || c.name, c.name]);
  }
  const firstScalarCol = scalars.length ? scalars[0][1] : null;

  const collections = root.relations.filter(r => r.kind === 'one-to-many');
  const refRels = root.relations.filter(
    r => r.kind === 'many-to-one-ref' && resolve(r.targetKey),
  );

  // the one refId column name every target shares, or null when they differ - then
  // only the ref's presence is asserted, never a column that may not exist
  const commonRefIdCol = rels => {
    const names = rels.map(r => refIdColOf(entityByKey.get(r.targetKey)));
    if (!names.length || names.some(n => !n)) return null;
    return new Set(names).size === 1 ? names[0] : null;
  };
  const refIdCol = commonRefIdCol(refRels);
  const collRefIdCol = commonRefIdCol(collections);

  let nestedCase = null;
  for (const rel of collections) {
    const target = entityByKey.get(rel.targetKey);
    const inner = (target?.relations ?? []).find(
      r => r.kind === 'many-to-one-ref' && resolve(r.targetKey),
    );
    if (inner) {
      nestedCase = { collection: rel.property, refProp: inner.property };
      break;
    }
  }

  const createEvent = (resource.notificationEvents ?? []).find(e => e.eventKind === 'Create');
  const emitMethod = host?.method ?? 'emitEvent';
  const eventRef = createEvent
    ? (host?.eventTypeStyle === 'literal'
        ? q(createEvent.eventName)
        : `${meta.eventTypeEnum}.${createEvent.enumMember}`)
    : null;

  /* ── constants this describe adds to the file head ── */
  const consts = [
    '',
    '/** The `@type` a create stamps on a payload that carries none. */',
    ...stringConst('AT_TYPE', defaultAtType(resource.name)),
    ...(hasAtType
      ? [
          '/** One the payload supplies instead, which must survive that default. */',
          ...stringConst('SUPPLIED_AT_TYPE', `Custom${resource.name}`),
        ]
      : []),
  ];
  if (scalars.length) {
    consts.push(
      '',
      '/** Each settable root scalar: the payload key it is read from -> its column. */',
      ...objectConst('SCALARS', 'Record<string, string>', scalars.map(([w, c]) => [w, q(c)])),
      '',
      'function scalarPayload(): AnyRec {',
      '  const out: AnyRec = {};',
      '  for (const w of Object.keys(SCALARS)) out[w] = `res-${SCALARS[w]}`;',
      '  return out;',
      '}',
    );
  }
  if (refRels.length) {
    consts.push(
      '',
      '/** Single refs: normalised into rows of their own, written before the aggregate. */',
      ...tupleConst('REF_PROPS', refRels.map(r => r.property)),
    );
  }
  if (nestedCase) {
    consts.push(
      '',
      '/** A collection whose rows carry a normalised ref row of their own. */',
      ...stringConst('NESTED_COLLECTION', nestedCase.collection),
      ...stringConst('NESTED_REF', nestedCase.refProp),
    );
  }

  /* ── the it()s, at their final indentation inside describe('create') ── */
  const body = [];

  body.push(
    "    it('persists every scalar and answers with the stored resource plus its href', async () => {",
    '      repo.findOne.mockResolvedValue(entity());',
    ...callLines('      ', 'const res = await service.create', [
      scalars.length ? 'scalarPayload() as never' : '{} as never',
    ]),
    '',
    '      const persisted = repo.save.mock.calls[0][0];',
    ...(scalars.length
      ? [
          '      for (const w of Object.keys(SCALARS)) {',
          '        expect(persisted[SCALARS[w]]).toBe(`res-${SCALARS[w]}`);',
          '      }',
        ]
      : []),
    `      expect(res${pkKey}).toBe(ID);`,
    '      expect(res.href).toBe(HREF);',
    '    });',
    '',
  );

  if (createEvent) {
    body.push(
      "    it('emits a create event carrying the mapped response', async () => {",
      '      repo.findOne.mockResolvedValue(entity());',
      '      const res = await service.create({} as never);',
      ...(host?.callStyle === 'object'
        ? [
            `      expect(eventEmitter.${emitMethod}).toHaveBeenCalledWith(`,
            '        expect.objectContaining({',
            `          eventType: ${eventRef},`,
            '          resourceId: ID,',
            `          resourceType: ${q(resource.name)},`,
            '          payload: res,',
            '        }),',
            '      );',
          ]
        : callLines('      ', `expect(eventEmitter.${emitMethod}).toHaveBeenCalledWith`, [
            eventRef,
            'ID',
            q(resource.name),
            'res',
          ])),
      '    });',
      '',
    );
  }

  body.push(
    `    it('keeps a client-supplied id and defaults @type to ${defaultAtType(resource.name)}', async () => {`,
    `      repo.findOne.mockResolvedValue(entity({ ${key(pk)}: 'chosen' }));`,
    `      await service.create({ ${key(pk)}: 'chosen' } as never);`,
    '      const persisted = repo.save.mock.calls[0][0];',
    `      expect(persisted${pkKey}).toBe('chosen');`,
    '      expect(persisted.atType).toBe(AT_TYPE);',
    '    });',
    '',
    hasAtType
      ? "    it('generates a uuid when no id is supplied and keeps a supplied @type', async () => {"
      : "    it('generates a uuid when no id is supplied', async () => {",
    '      repo.findOne.mockResolvedValue(entity());',
    hasAtType
      ? "      await service.create({ '@type': SUPPLIED_AT_TYPE } as never);"
      : '      await service.create({} as never);',
    '      const persisted = repo.save.mock.calls[0][0];',
    `      expect(persisted${pkKey}).toMatch(/^[0-9a-f-]{36}$/);`,
    ...(hasAtType
      ? ['      expect(persisted.atType).toBe(SUPPLIED_AT_TYPE);']
      : []),
    '    });',
    '',
  );

  if (root.softDelete) {
    body.push(
      "    it('clears the soft-delete stamps so a reused id is resurrected', async () => {",
      '      // A client may reuse the id of a row that was soft-deleted. Left stamped,',
      '      // save() updates a row findEntity cannot see, and the POST answers 404',
      '      // on the very id it just wrote.',
      '      repo.findOne.mockResolvedValue(entity());',
      `      await service.create({ ${key(pk)}: 'chosen' } as never);`,
      '      const persisted = repo.save.mock.calls[0][0];',
      `      expect(persisted.${SOFT_DELETE_TIMESTAMP_COLUMN}).toBeNull();`,
      ...SOFT_DELETE_ATTRIBUTION_COLUMNS.map(
        c => `      expect(persisted.${c}).toBeUndefined();`,
      ),
      '    });',
      '',
    );
  }

  if (refRels.length) {
    body.push(
      "    it('writes the single refs as rows of their own before the aggregate', async () => {",
      '      repo.findOne.mockResolvedValue(entity());',
      '      const payload: AnyRec = {};',
      '      for (const p of REF_PROPS) payload[p] = { id: `${p}-9` };',
      '      await service.create(payload as never);',
      '',
      '      const persisted = repo.save.mock.calls[0][0];',
      '      for (const p of REF_PROPS) {',
      '        const ref = persisted[p];',
      '        expect(ref).toBeDefined();',
      ...(refIdCol ? ['        expect(ref.' + refIdCol + ').toBe(`${p}-9`);'] : []),
      '      }',
      '      // otherwise the aggregate FK points at a row that was never written',
      '      expect(refSave).toHaveBeenCalled();',
      '      for (const order of refSave.mock.invocationCallOrder) {',
      '        expect(order).toBeLessThan(repo.save.mock.invocationCallOrder[0]);',
      '      }',
      '    });',
      '',
    );
  }

  if (nestedCase) {
    body.push(
      "    it('writes a nested ref row before the aggregate that points at it', async () => {",
      '      repo.findOne.mockResolvedValue(entity());',
      '      const payload: AnyRec = {};',
      '      const nestedRow: AnyRec = { id: `${NESTED_COLLECTION}-a` };',
      '      nestedRow[NESTED_REF] = { id: `${NESTED_REF}-9` };',
      '      payload[NESTED_COLLECTION] = [nestedRow];',
      '      await service.create(payload as never);',
      '',
      '      const persisted = repo.save.mock.calls[0][0];',
      '      const nested = persisted[NESTED_COLLECTION][0][NESTED_REF];',
      '      expect(nested).toBeDefined();',
      '      // cascade does not reach a ref owned by a row that is itself cascaded',
      '      expect(refSave).toHaveBeenCalledWith(nested);',
      '      for (const order of refSave.mock.invocationCallOrder) {',
      '        expect(order).toBeLessThan(repo.save.mock.invocationCallOrder[0]);',
      '      }',
      '    });',
      '',
    );
  }

  if (collections.length) {
    body.push(
      "    it('numbers each collection row by its position in the payload', async () => {",
      `      // a row carrying no sortOrder sorts at ${SORT_ORDER_FALLBACK} on the way out, so the`,
      `      // first row written has to carry ${SORT_ORDER_FALLBACK} for both paths to agree`,
      '      repo.findOne.mockResolvedValue(entity());',
      '      const payload: AnyRec = {};',
      '      for (const c of COLLECTIONS) {',
      '        payload[c] = [{ id: `${c}-a` }, { id: `${c}-b` }];',
      '      }',
      '      await service.create(payload as never);',
      '',
      '      const persisted = repo.save.mock.calls[0][0];',
      '      for (const c of COLLECTIONS) {',
      '        const rows = persisted[c] as AnyRec[];',
      ...expectEqualArray('        ', 'rows.map((r) => r.sortOrder)', [
        String(SORT_ORDER_FALLBACK),
        String(SORT_ORDER_FALLBACK + 1),
      ]),
      ...(collRefIdCol
        ? expectEqualArray('        ', `rows.map((r) => r.${collRefIdCol})`, [
            '`${c}-a`',
            '`${c}-b`',
          ])
        : []),
      '      }',
      '    });',
      '',
    );
  }

  if (refRels.length || collections.length) {
    const what = [
      refRels.length ? 'the single refs unset' : null,
      collections.length ? 'every collection empty' : null,
    ].filter(Boolean).join(' and ');
    body.push(
      `    it('leaves ${what} when the payload omits them', async () => {`,
      '      repo.findOne.mockResolvedValue(entity());',
      '      await service.create({} as never);',
      '      const persisted = repo.save.mock.calls[0][0];',
      ...(refRels.length
        ? ['      for (const p of REF_PROPS) expect(persisted[p]).toBeUndefined();']
        : []),
      ...(collections.length
        ? ['      for (const c of COLLECTIONS) expect(persisted[c]).toEqual([]);']
        : []),
      '      expect(refSave).not.toHaveBeenCalled();',
      '    });',
      '',
    );
  }

  const hookEntries = [[pk, q('from-hook')]];
  if (firstScalarCol) hookEntries.push([scalars[0][0], q('res-from-hook')]);
  body.push(
    "    it('builds from the payload the beforeCreate hook returns, not the dto', async () => {",
    '      // beforeCreate lives in a file tmfgen does not manage. What it returns is',
    '      // its owner\'s business, so it is SPIED here rather than asserted on: what',
    '      // is under test is that create builds from the value it got back.',
    ...indented('      ', objectConst('HOOK_PAYLOAD', 'AnyRec', hookEntries, 6)),
    ...callLines('      ', "jest.spyOn(hooks, 'beforeCreate').mockResolvedValue", [
      'HOOK_PAYLOAD',
    ]),
    '      repo.findOne.mockResolvedValue(entity());',
    `      await service.create({ ${key(pk)}: 'ignored' } as never);`,
    '',
    '      const persisted = repo.save.mock.calls[0][0];',
    `      expect(persisted${pkKey}).toBe('from-hook');`,
    ...(firstScalarCol
      ? [
          `      expect(persisted${IDENT.test(firstScalarCol) ? `.${firstScalarCol}` : `[${q(firstScalarCol)}]`}).toBe('res-from-hook');`,
        ]
      : []),
    '    });',
  );

  const ctorArgs = [
    'repo as never',
    ...Array.from({ length: Math.max(0, repoCount - 1) }, () => 'makeRepo() as never'),
    'dataSource as never',
    'eventEmitter as never',
  ];

  return {
    consts,
    hooksImport: `import * as hooks from '${src}/${fileBase}.hooks';`,
    lines: [
      `describe(${q(svcClass)}, () => {`,
      '  let repo: AnyRec;',
      '  let refSave: jest.Mock;',
      '  let dataSource: AnyRec;',
      '  let eventEmitter: AnyRec;',
      `  let service: ${svcClass};`,
      '',
      '  beforeEach(() => {',
      '    repo = makeRepo();',
      '    refSave = jest.fn(async (e: AnyRec) => e);',
      '    dataSource = {',
      '      getRepository: jest.fn(() => ({',
      '        create: jest.fn((v: AnyRec) => v),',
      '        findOne: jest.fn(async () => null),',
      '        save: refSave,',
      '      })),',
      '    };',
      `    eventEmitter = { ${emitMethod}: jest.fn() };`,
      ...callLines('    ', `service = new ${svcClass}`, ctorArgs),
      '  });',
      '',
      '  afterEach(() => {',
      '    jest.restoreAllMocks();',
      '  });',
      '',
      "  describe('create', () => {",
      ...body,
      '  });',
      '});',
      '',
    ],
  };
}

/**
 * The controller describe: route metadata, and the delegation from controller to
 * service.
 *
 * Every `it()` is gated on the operation that backs it, because emit/controller.mjs
 * emits a route ONLY for a declared operation - TMF673's GeographicAddress is
 * list + retrieve and has no create/update/delete method to call at all. The
 * Nest-constructibility `it()` is unconditional, which is what makes this describe
 * non-empty for every resource that has any operation, and therefore what lets the
 * file exist for a root-only resource that the entities describe alone could not
 * fill.
 *
 * The call SHAPES are read off renderController, not off the reference:
 *   flat     create(dto, res) / findAll(query) / findOne(id, fields)
 *            / update(id, dto) / remove(id)
 *   nested   every one of those takes the parent @Param()s FIRST, and the
 *            service call carries them as `{ ...dto, p }` (create), `{ ...query, p }`
 *            (findAll) or a trailing `{ p }` scope argument (findOne, update,
 *            remove - remove's is the FOURTH argument, after two undefineds).
 *
 * ROUTE_PATH is `<meta.basePath>/<routeSegment>` because @Controller() is written
 * as a template literal over the base-path constant; PATH_METADATA holds the
 * evaluated string. The segment is nested.routeSegment (`topic/:topicId/event`),
 * NOT the nested.hrefSegment HREF uses.
 */
function controllerBlock({ resource, root, nested, meta }) {
  const ops = resource.operations ?? {};
  const ctrlClass = `${resource.name}Controller`;
  const svcClass = `${resource.name}Service`;
  const parents = nested?.params ?? [];
  const parentArgs = parents.map(p => q(`${p}-1`));
  const scopeArg = parents.length ? 'PARENTS' : null;

  const pkCol = root.columns.find(c => c.primary);
  const pk = pkCol ? pkCol.name : 'id';
  const scalar = root.columns.find(
    c => !isHousekeeping(c) && !c.primary && c.name !== 'atType',
  );
  const field = scalar ? scalar.name : pk;

  const routeSegment = nested ? nested.routeSegment : resource.pathSegment;

  const consts = [
    '/** The route Nest registers from @Controller(`${BASE_PATH}/...`). */',
    ...stringConst('ROUTE_PATH', `${meta.basePath}/${routeSegment}`),
    '',
    "/** The id every delegation asserts on, and the scalar the write paths move. */",
    ...stringConst('ID', 'res-1'),
    ...stringConst('FIELD', field),
  ];
  if (ops.list) consts.push(...objectConst('LIST_QUERY', null, [['limit', '5']]));
  if (ops.create) {
    consts.push(...objectConst('CREATE_BODY', null, [[field, q(`res-${field}`)]]));
  }
  if (ops.update) {
    consts.push(...objectConst('UPDATE_BODY', null, [[field, q('res-updated')]]));
  }
  if (parents.length) {
    consts.push(
      '',
      '/** The parent keys the nested routes carry, as the service receives them. */',
      ...objectConst(
        'PARENTS',
        'Record<string, string>',
        parents.map(p => [p, q(`${p}-1`)]),
      ),
    );
    if (ops.create) consts.push('const CREATE_EXPECTED = { ...CREATE_BODY, ...PARENTS };');
    if (ops.list) consts.push('const LIST_EXPECTED = { ...LIST_QUERY, ...PARENTS };');
  }
  consts.push('');

  const createExpected = parents.length ? 'CREATE_EXPECTED' : 'CREATE_BODY';
  const listExpected = parents.length ? 'LIST_EXPECTED' : 'LIST_QUERY';

  // The service double carries only the methods the controller can reach.
  const double = [];
  if (ops.create) {
    double.push(...jestFnEntry('      ', 'create', [[pk, 'ID'], ['href', 'HREF']]));
  }
  if (ops.list) {
    double.push(...jestFnEntry('      ', 'findAll', [['data', '[]'], ['total', '0']]));
  }
  if (ops.retrieve) double.push(...jestFnEntry('      ', 'findOne', [[pk, 'ID']]));
  if (ops.update) {
    const entries = field === pk ? [[pk, q('res-updated')]] : [[pk, 'ID'], [field, q('res-updated')]];
    double.push(...jestFnEntry('      ', 'update', entries));
  }
  if (ops.delete) double.push('      remove: jest.fn(async () => undefined),');

  const body = [];

  if (ops.create) {
    body.push(
      "  it('sets the Location header from the created resource href', async () => {",
      '    const res = { location: jest.fn() };',
      ...callLines('    ', 'const out = await ctrl.create', [
        ...parentArgs,
        'CREATE_BODY as never',
        'res as never',
      ]),
      `    expect(svc.create).toHaveBeenCalledWith(${createExpected});`,
      '    expect(res.location).toHaveBeenCalledWith(HREF);',
      `    expect(out${IDENT.test(pk) ? `.${pk}` : `[${q(pk)}]`}).toBe(ID);`,
      '  });',
      '',
      "  it('omits the Location header when the created resource has no href', async () => {",
      `    svc.create.mockResolvedValue({ ${key(pk)}: ID });`,
      '    const res = { location: jest.fn() };',
      ...callLines('    ', 'await ctrl.create', [...parentArgs, '{} as never', 'res as never']),
      '    expect(res.location).not.toHaveBeenCalled();',
      '  });',
      '',
    );
  }

  if (ops.list) {
    body.push(
      "  it('passes the query through to findAll', async () => {",
      ...callLines('    ', 'await ctrl.findAll', [...parentArgs, 'LIST_QUERY as never']),
      `    expect(svc.findAll).toHaveBeenCalledWith(${listExpected});`,
      '  });',
      '',
    );
  }

  if (ops.retrieve) {
    body.push(
      "  it('forwards the id and the field selection to findOne', async () => {",
      ...callLines('    ', 'await ctrl.findOne', [...parentArgs, 'ID', 'FIELD']),
      ...callLines('    ', 'expect(svc.findOne).toHaveBeenCalledWith', [
        'ID',
        'FIELD',
        ...(scopeArg ? [scopeArg] : []),
      ]),
      '  });',
      '',
    );
  }

  if (ops.update) {
    body.push(
      "  it('forwards the id and the payload to update', async () => {",
      ...callLines('    ', 'const out = await ctrl.update', [
        ...parentArgs,
        'ID',
        'UPDATE_BODY as never',
      ]),
      ...callLines('    ', 'expect(svc.update).toHaveBeenCalledWith', [
        'ID',
        'UPDATE_BODY',
        ...(scopeArg ? [scopeArg] : []),
      ]),
      "    expect(out[FIELD]).toBe('res-updated');",
      '  });',
      '',
    );
  }

  if (ops.delete) {
    body.push(
      "  it('delegates the delete route', async () => {",
      ...callLines('    ', 'await ctrl.remove', [...parentArgs, 'ID']),
      ...callLines('    ', 'expect(svc.remove).toHaveBeenCalledWith', [
        'ID',
        ...(scopeArg ? ['undefined', 'undefined', scopeArg] : []),
      ]),
      '  });',
      '',
    );
  }

  const providersInline = `      providers: [{ provide: ${svcClass}, useValue: svc }],`;
  body.push(
    "  it('is constructible by Nest with its route metadata intact', async () => {",
    '    // A concrete controller carrying no decorator of its own emits no',
    '    // constructor `design:paramtypes`, so Nest builds it with zero arguments',
    '    // and every route 500s; losing only @Controller() keeps injection working',
    '    // but silently unmounts the routes. Both are checked separately.',
    '    const moduleRef = await Test.createTestingModule({',
    `      controllers: [${ctrlClass}],`,
    ...(providersInline.length <= PRINT_WIDTH
      ? [providersInline]
      : [
          '      providers: [',
          `        { provide: ${svcClass}, useValue: svc },`,
          '      ],',
        ]),
    '    }).compile();',
    '',
    ...callLines('    ', 'const resolved = moduleRef.get', [ctrlClass], ' as unknown as AnyRec;'),
    '    expect(resolved.service).toBe(svc);',
    ...callLines('    ', 'const paramtypes = Reflect.getMetadata', [
      q('design:paramtypes'),
      ctrlClass,
    ]),
    ...expectEqualArray('    ', 'paramtypes', [svcClass]),
    ...callLines('    ', 'const routePath = Reflect.getMetadata', ['PATH_METADATA', ctrlClass]),
    '    expect(routePath).toBe(ROUTE_PATH);',
    '  });',
  );

  const writeRoutes = [
    ops.create ? ['create', `Create${resource.name}Dto`] : null,
    ops.update ? ['update', `Update${resource.name}Dto`] : null,
  ].filter(Boolean);

  const helper = [];
  if (writeRoutes.length) {
    helper.push(
      "/** The design:paramtype Nest hands ValidationPipe for a route's @Body(). */",
      'function bodyParamType(route: string): unknown {',
      ...callLines('  ', 'const args = Reflect.getMetadata', [
        'ROUTE_ARGS_METADATA',
        ctrlClass,
        'route',
      ], ' as AnyRec;'),
      '  const prefix = `${RouteParamtypes.BODY}:`;',
      '  const bodyKey = Object.keys(args).find((k) => k.startsWith(prefix));',
      '  expect(bodyKey).toBeDefined();',
      "  const index = Number((bodyKey as string).split(':')[1]);",
      ...callLines('  ', 'const types = Reflect.getMetadata', [
        q('design:paramtypes'),
        `${ctrlClass}.prototype`,
        'route',
      ]),
      '  return types[index];',
      '}',
      '',
    );
    body.push(
      '',
      "  it('types every write body as its DTO class, so ValidationPipe has a schema', () => {",
      '    // ValidationPipe validates against the parameter\'s design:paramtype. A body',
      '    // left as `any`/`unknown` erases to Object, which accepts every payload',
      '    // unchecked and makes Swagger emit no request body schema.',
      ...writeRoutes.map(([route, dto]) => `    expect(bodyParamType(${q(route)})).toBe(${dto});`),
      '  });',
    );
  }

  return {
    consts,
    dtoImports: writeRoutes.map(([, dto]) => dto),
    lines: [
      ...helper,
      `describe(${q(ctrlClass)}, () => {`,
      '  let svc: AnyRec;',
      `  let ctrl: ${ctrlClass};`,
      '',
      '  beforeEach(() => {',
      '    svc = {',
      ...double,
      '    };',
      ...callLines('    ', `ctrl = new ${ctrlClass}`, ['svc as never']),
      '  });',
      '',
      ...body,
      '});',
      '',
    ],
  };
}

/** The one file for one resource, or null when there is nothing worth asserting. */
function specFor({ resource, plan, dir, nested }, deps) {
  const { resolve, entityDirOf, meta, host } = deps;

  // A resource with no operations has no routes and no service surface a caller
  // can reach; the shared files still cover its entities.
  if (!Object.values(resource.operations ?? {}).some(Boolean)) return null;

  const root = plan.entities.find(e => e.kind === 'root');
  if (!root) return null;
  if (!resolve(root.key)) return null;

  // The same de-duplication renderService applies: one mapper, and one entity
  // file, per distinct class name, with the LAST plan entity winning the class.
  const byClass = new Map();
  for (const e of plan.entities) {
    const self = resolve(e.key);
    if (self) byClass.set(self.className, e);
  }

  // Task 1 skipped a root-only resource here: with only the entities describe -
  // whose one assertion the shared test/entities.spec.ts barrel already makes -
  // the file would have carried no test at all, and Jest fails an empty suite
  // outright ("Your test suite must contain at least one test"). The controller
  // describe below always contributes at least the Nest-constructibility it(),
  // so every resource with an operation now gets its file.

  const entityClasses = [...byClass.keys()].sort();
  const fileBase = kebab(resource.name);
  const src = `../../src/${dir}`;

  const collections = root.relations.filter(r => r.kind === 'one-to-many');
  const hrefSegments = [];
  const rowAtTypes = [];
  for (const rel of collections) {
    const target = resolve(rel.targetKey);
    if (!target) continue;
    rowAtTypes.push([rel.property, q(target.className)]);
    // the entity whose mapper was actually emitted for that class
    const emitted = byClass.get(target.className);
    if (emitted && emitted.kind === 'child' && !emitted.refLike && emitted.ownerField) {
      hrefSegments.push([rel.property, q(emitted.ownerField)]);
    }
  }

  const segment = nested ? nested.hrefSegment : resource.pathSegment;
  const href = `/${meta.basePath}/${segment}/res-1`;

  const scalarLines = [];
  for (const c of root.columns) {
    if (isHousekeeping(c)) continue;
    const value = c.primary
      ? 'res-1'
      : c.name === 'atType'
        ? defaultAtType(resource.name)
        : `res-${c.name}`;
    scalarLines.push(...propLine(c.name, q(value), '    '));
  }

  const ctrl = controllerBlock({ resource, root, nested, meta });
  const svc = serviceBlock({
    resource, plan, root, meta, host, resolve, src, fileBase,
  });

  const lines = [
    BANNER,
    '/**',
    ` * ${resource.name}`,
    ' *',
    ' * The generated service and controller, against mocked repositories.',
    ' *',
    ' * TypeORM is mocked rather than run: a service emitted with --db postgres',
    ' * carries postgres column types and will not boot on sqlite, so an in-memory',
    ' * database is not an option.',
    ' *',
    ' * Every literal below is derived from this resource, never hand-written: see',
    ' * the mapping table in emit/spec/resource.mjs for where each one comes from.',
    ' */',
    ctrl.dtoImports.length
      ? "import { PATH_METADATA, ROUTE_ARGS_METADATA } from '@nestjs/common/constants';"
      : "import { PATH_METADATA } from '@nestjs/common/constants';",
    ...(ctrl.dtoImports.length
      ? ["import { RouteParamtypes } from '@nestjs/common/enums/route-paramtypes.enum';"]
      : []),
    "import { Test } from '@nestjs/testing';",
    `import { ${resource.name}Service } from '${src}/${fileBase}.service';`,
    `import { ${resource.name}Controller } from '${src}/${fileBase}.controller';`,
    `import { ${meta.eventTypeEnum} } from '../../src/event/event-types';`,
    ...(ctrl.dtoImports.length
      ? importLine(ctrl.dtoImports, `${src}/dto`)
      : []),
    ...entityClasses.map(
      cn => `import { ${cn} } from '../../src/${entityDirOf(cn) ?? dir}/entities/${kebab(cn)}.entity';`,
    ),
    svc.hooksImport,
    '',
    'type AnyRec = Record<string, any>;',
    '',
    ...REPO_FIXTURE,
    '',
    ...stringConst('HREF', href),
    '',
    ...ctrl.consts,
  ];

  if (collections.length) {
    lines.push(
      '/** The owner-bound collections this resource maps. */',
      ...tupleConst('COLLECTIONS', collections.map(r => r.property)),
      '',
      "/** The path segment each collection's row mapper writes into its href. */",
      ...objectConst('HREF_SEGMENT', 'Record<string, string>', hrefSegments),
      '',
      "/** The `@type` each collection's rows carry: their own entity class name. */",
      ...objectConst('ROW_AT_TYPE', 'Record<string, string>', rowAtTypes),
      '',
      'function row(collection: string, index: number): AnyRec {',
      '  return {',
      '    id: `${collection}-row-${index}`,',
      '    refId: `${collection}-ref-${index}`,',
      '    atType: ROW_AT_TYPE[collection],',
      '    sortOrder: index,',
      '  };',
      '}',
      '',
    );
  }

  // svc.consts opens with a blank separator, which the block above already
  // supplied - Prettier collapses two blank lines into one, so emitting both
  // would fail --check on every file.
  lines.push(...svc.consts.slice(1), '');

  lines.push(
    'function entity(over: AnyRec = {}): AnyRec {',
    '  return {',
    ...scalarLines,
    ...collections.flatMap(r => collectionProp(r.property, '    ')),
    '    ...over,',
    '  };',
    '}',
    '',
    `describe(${q(`${resource.name} entities`)}, () => {`,
    "  it('are constructible, so the mocked repositories stand in for real rows', () => {",
    ...forOfClasses(entityClasses, '    '),
    '      expect(new (E as new () => object)()).toBeInstanceOf(E as never);',
    '    }',
    '  });',
    '});',
    '',
    ...svc.lines,
    ...ctrl.lines,
  );

  return { rel: `test/${dir}/${fileBase}.service.spec.ts`, text: lines.join('\n') };
}

/**
 * One spec file per resource of the IR being emitted.
 *
 * @param {{ plans: object[], resolve: Function, entityDirOf: Function,
 *           meta: object }} ctx
 * @returns {{ rel: string, text: string }[]}
 */
export function emitResourceSpecs(ctx) {
  const { plans, resolve, entityDirOf, meta, host = null } = ctx;
  if (!plans?.length || !resolve || !entityDirOf || !meta) return [];
  const out = [];
  for (const p of plans) {
    const file = specFor(p, { resolve, entityDirOf, meta, host });
    if (file) out.push(file);
  }
  return out;
}
