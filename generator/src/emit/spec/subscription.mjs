import { pascal } from '../../ir/naming.mjs';
import {
  DEFAULT_OFFSET,
  DEFAULT_LIMIT,
  LATEST_ORDER_COLUMN,
  LATEST_ORDER_DIRECTION,
  HUB_PATH_SEGMENT,
} from '../behaviour.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';

/**
 * test/subscription/subscription.spec.ts - SubscriptionService (create, TMF630 list,
 * retrieve, delete) plus EVERY hosted component's hub controller (Hub-shaped responses).
 *
 * Almost entirely fixed text: every component shares the same SubscriptionService
 * and the same hub-controller shape (see emit/wiring.mjs's subscriptionController).
 * The only per-component parts are the controller's class name and file, both
 * taken from the manifest entry's `slug` - the same field wiring.mjs builds the
 * controllers from, so the two cannot disagree about a name.
 *
 * wiring.mjs writes ONE hub controller per hosted component. Built from a single
 * IR this suite tested one of them and ignored the rest; it is built from the
 * manifest union instead, so a three-component service gets three controller
 * suites.
 *
 * The paging defaults (skip: 0, take: 20), the newest-first order and the /hub/
 * route segment are interpolated from behaviour.mjs rather than hardcoded, so
 * this suite cannot drift from what the generator actually produces.
 */

/** The hub-controller suite for one hosted component. */
function controllerSuite(cls) {
  return [
    `describe('${cls}', () => {`,
    '  let svc: AnyRec;',
    `  let ctrl: ${cls};`,
    "  const row = { id: 's1', callback: 'https://a/hook', query: 'eventType=E', createdDate: new Date() };",
    '',
    '  beforeEach(() => {',
    '    svc = {',
    '      findAll: jest.fn(async () => ({ data: [row], total: 1 })),',
    '      findOne: jest.fn(async () => row),',
    "      create: jest.fn(async () => ({ id: 's1', callback: 'https://a/hook', createdDate: new Date() })),",
    '      remove: jest.fn(async () => undefined),',
    '    };',
    `    ctrl = new ${cls}(svc as never);`,
    '  });',
    '',
    "  it('passes the query on and parses offset and limit', async () => {",
    "    const query = { offset: '10', limit: '5', callback: 'https://a/hook' };",
    '    await ctrl.findAll(query);',
    '    expect(svc.findAll).toHaveBeenCalledWith(query, 10, 5);',
    '  });',
    '',
    "  it('falls back to 0/20 when they are absent or unparseable', async () => {",
    '    await ctrl.findAll({});',
    `    expect(svc.findAll).toHaveBeenCalledWith({}, ${DEFAULT_OFFSET}, ${DEFAULT_LIMIT});`,
    "    await ctrl.findAll({ offset: 'abc', limit: 'def' });",
    `    expect(svc.findAll).toHaveBeenLastCalledWith({ offset: 'abc', limit: 'def' }, ${DEFAULT_OFFSET}, ${DEFAULT_LIMIT});`,
    '  });',
    '',
    "  it('lists Hubs in the spec shape, without internal columns', async () => {",
    '    const { data, total } = await ctrl.findAll({});',
    '    expect(total).toBe(1);',
    '    expect(data[0]).toEqual({',
    "      id: 's1',",
    `      href: expect.stringContaining('/${HUB_PATH_SEGMENT}/s1'),`,
    "      callback: 'https://a/hook',",
    "      query: 'eventType=E',",
    "      '@type': 'Hub',",
    '    });',
    '  });',
    '',
    "  it('retrieves one Hub', async () => {",
    "    const hub = await ctrl.findOne('s1');",
    "    expect(svc.findOne).toHaveBeenCalledWith('s1');",
    "    expect(hub['@type']).toBe('Hub');",
    "    expect(hub).not.toHaveProperty('createdDate');",
    '  });',
    '',
    "  it('sets Location and echoes the href on create', async () => {",
    '    const res = { location: jest.fn() };',
    '    const out = await ctrl.create(',
    "      { callback: 'https://a/hook', '@type': 'Hub' } as never,",
    '      res as never,',
    '    );',
    '    expect(res.location).toHaveBeenCalledWith(',
    `      expect.stringContaining('/${HUB_PATH_SEGMENT}/s1'),`,
    '    );',
    `    expect(out.href).toContain('/${HUB_PATH_SEGMENT}/s1');`,
    "    expect(out.id).toBe('s1');",
    "    expect(out).not.toHaveProperty('query');",
    "    expect(out).not.toHaveProperty('createdDate');",
    '  });',
    '',
    "  it('delegates delete', async () => {",
    "    await ctrl.remove('s1');",
    "    expect(svc.remove).toHaveBeenCalledWith('s1');",
    '  });',
    '});',
    '',
  ];
}

export function emitSubscriptionSpec({ components }) {
  if (!components.length) return null;

  const ctrls = components.map(c => ({
    cls: `${pascal(c.slug)}SubscriptionController`,
    file: `${c.slug}-subscription.controller`,
  }));

  const lines = [
    BANNER,
    "import { NotFoundException } from '@nestjs/common';",
    "import { SubscriptionService } from '../../src/subscription/subscription.service';",
    ...ctrls.map(c => `import { ${c.cls} } from '../../src/subscription/${c.file}';`),
    '',
    'type AnyRec = Record<string, any>;',
    '',
    "describe('SubscriptionService', () => {",
    '  let repo: AnyRec;',
    '  let qb: AnyRec;',
    '  let svc: SubscriptionService;',
    '',
    '  beforeEach(() => {',
    '    qb = {',
    '      andWhere: jest.fn(() => qb),',
    '      addOrderBy: jest.fn(() => qb),',
    '      skip: jest.fn(() => qb),',
    '      take: jest.fn(() => qb),',
    '      getCount: jest.fn(async () => 1),',
    "      getMany: jest.fn(async () => [{ id: 's1' }]),",
    '      // common/filter renders each filter scope as e.id IN <subquery>',
    '      subQuery: jest.fn(() => {',
    "        const sub: AnyRec = { getQuery: () => '(sub)' };",
    "        for (const m of ['from', 'select', 'innerJoin', 'leftJoin', 'where']) sub[m] = jest.fn(() => sub);",
    '        return sub;',
    '      }),',
    '      getParameters: jest.fn(() => ({})),',
    '      setParameters: jest.fn(() => qb),',
    '    };',
    '    repo = {',
    '      create: jest.fn((v: AnyRec) => ({ ...v })),',
    '      save: jest.fn(async (v: AnyRec) => v),',
    '      findOne: jest.fn(),',
    '      createQueryBuilder: jest.fn(() => qb),',
    '      delete: jest.fn(async () => ({ affected: 1 })),',
    '    };',
    '    svc = new SubscriptionService(repo as never);',
    '  });',
    '',
    "  it('creates a subscription with a generated id', async () => {",
    '    const res = await svc.create({',
    "      callback: 'https://a/hook',",
    "      query: 'eventType=E',",
    '    } as never);',
    '    const arg = repo.create.mock.calls[0][0];',
    "    expect(arg.callback).toBe('https://a/hook');",
    "    expect(arg.query).toBe('eventType=E');",
    '    expect(arg.id).toMatch(/[0-9a-f-]{36}/);',
    "    expect(res.callback).toBe('https://a/hook');",
    '  });',
    '',
    "  it('pages with the supplied offset and limit, newest first', async () => {",
    '    const res = await svc.findAll({}, 10, 5);',
    '    expect(qb.skip).toHaveBeenCalledWith(10);',
    '    expect(qb.take).toHaveBeenCalledWith(5);',
    `    expect(qb.addOrderBy).toHaveBeenCalledWith('e.${LATEST_ORDER_COLUMN}', '${LATEST_ORDER_DIRECTION}');`,
    "    expect(res).toEqual({ data: [{ id: 's1' }], total: 1 });",
    '  });',
    '',
    "  it('defaults to the first page of twenty', async () => {",
    '    await svc.findAll();',
    `    expect(qb.skip).toHaveBeenCalledWith(${DEFAULT_OFFSET});`,
    `    expect(qb.take).toHaveBeenCalledWith(${DEFAULT_LIMIT});`,
    '  });',
    '',
    "  it('a client sort replaces the default order', async () => {",
    "    await svc.findAll({ sort: '-callback' });",
    "    expect(qb.addOrderBy).toHaveBeenCalledWith('e.callback', 'DESC');",
    `    expect(qb.addOrderBy).not.toHaveBeenCalledWith('e.${LATEST_ORDER_COLUMN}', '${LATEST_ORDER_DIRECTION}');`,
    '  });',
    '',
    "  it('filters by Hub attributes (TMF630)', async () => {",
    "    await svc.findAll({ callback: 'https://a/hook' });",
    "    expect(qb.andWhere).toHaveBeenCalledWith('e.id IN (sub)');",
    "    expect(qb.setParameters).toHaveBeenCalledWith({ flt1: 'https://a/hook' });",
    '  });',
    '',
    "  it('retrieves one subscription, 404 when it is gone', async () => {",
    "    repo.findOne.mockResolvedValueOnce({ id: 's1' });",
    "    await expect(svc.findOne('s1')).resolves.toEqual({ id: 's1' });",
    '    repo.findOne.mockResolvedValueOnce(null);',
    "    await expect(svc.findOne('gone')).rejects.toBeInstanceOf(NotFoundException);",
    '  });',
    '',
    "  it('removes by id', async () => {",
    "    await svc.remove('s1');",
    "    expect(repo.delete).toHaveBeenCalledWith('s1');",
    '  });',
    '});',
    '',
    ...ctrls.flatMap(c => controllerSuite(c.cls)),
  ];
  return { rel: 'test/subscription/subscription.spec.ts', text: lines.join('\n') };
}
