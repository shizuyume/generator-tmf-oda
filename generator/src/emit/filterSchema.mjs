// filterSchema.mjs — emits src/<dir>/<dir>.filter.ts: what a resource's list can be filtered and
// sorted on (TMF630 attribute style + JSONPath `filter=`), derived from its entity plan.
//
//   attrs   the root's own columns that are on the wire, by wire name (@type, href, …)
//   refs    single references held by the root (many-to-one), filterable by their columns
//   arrays  one-to-many children (one level), each with its own attrs + refs
// The runtime (common/filter) translates every condition into a bound-parameter subquery over
// these properties only — anything else in a filter answers 400.
import { kebab } from '../ir/naming.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';
const INTERNAL = new Set(['deletedAt', 'deletedBy', 'deletedReason', 'sortOrder']);

/** Columns the generator adds (audit / soft delete): never in a response, so never filterable. */
const isHousekeeping = (c) => !!(c.housekeeping || c.createDateColumn || c.updateDateColumn || c.deleteDateColumn);

/** Same inverse the response mapper uses (service.mjs responseKey). */
function wireKey(col) {
  if (col.sourceProp) return col.sourceProp;
  if (col.expose) return col.expose;
  return col.name;
}

export function filterType(col) {
  if (col.enumValues || col.tsType === 'string') return 'string';
  if (col.tsType === 'number') return 'number';
  if (col.tsType === 'boolean') return 'boolean';
  if (col.tsType === 'Date') return 'date';
  return null; // json, objects: not filterable
}

/** Wire name → { property, type }, in column order; the surrogate key is skipped when a column carries the wire id. */
function attrsOf(entity) {
  const carriesWireId = entity.columns.some((c) => !c.primary && wireKey(c) === 'id');
  const out = [];
  for (const c of entity.columns) {
    if (INTERNAL.has(c.name) || isHousekeeping(c)) continue;
    if (c.primary && carriesWireId) continue;
    const type = filterType(c);
    if (!type) continue;
    const key = wireKey(c);
    if (out.some(([k]) => k === key)) continue;
    out.push([key, { property: c.name, type }]);
  }
  return out;
}

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const keyOf = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : q(k));

function renderAttrs(attrs, indent) {
  if (!attrs.length) return '{}';
  const pad = ' '.repeat(indent);
  return `{\n${attrs.map(([k, a]) => `${pad}  ${keyOf(k)}: { property: ${q(a.property)}, type: ${q(a.type)} },`).join('\n')}\n${pad}}`;
}

function renderRefs(entity, entityOf, indent) {
  const refs = (entity.relations ?? []).filter((r) => r.kind === 'many-to-one-ref');
  if (!refs.length) return '{}';
  const pad = ' '.repeat(indent);
  const lines = refs.map((r) => {
    const target = entityOf(r.targetKey);
    return `${pad}  ${keyOf(r.property)}: {\n${pad}    relation: ${q(r.property)},\n${pad}    attrs: ${renderAttrs(target ? attrsOf(target) : [], indent + 4)},\n${pad}  },`;
  });
  return `{\n${lines.join('\n')}\n${pad}}`;
}

/**
 * @param resource IR resource
 * @param plan     buildEntityPlan(resource)
 * @param ctx      { resolve, importPathFor, parentParams }
 */
export function renderFilterSchema(resource, plan, ctx) {
  const { resolve, importPathFor, parentParams = [] } = ctx;
  const entityOf = (key) => plan.entities.find((e) => e.key === key) ?? null;
  const root = plan.entities.find((e) => e.kind === 'root');
  const children = plan.entities.filter((e) => e.kind === 'child' && e.ownerKey === root.key);
  const classOf = (e) => resolve(e.key).className;
  const classes = [...new Set([root, ...children].map(classOf))];
  const constName = `${kebab(resource.name).replace(/-/g, '_').toUpperCase()}_FILTER`;

  const arrays = children.map((c) => {
    const wire = c.key.split('.').pop();
    return `    ${keyOf(wire)}: {\n      entity: ${classOf(c)},\n      attrs: ${renderAttrs(attrsOf(c), 6)},\n      refs: ${renderRefs(c, entityOf, 6)},\n    },`;
  });

  // the generator's own audit timestamps: not spec attributes, but what a list is naturally
  // ordered and narrowed by (newest first, updated since) - the neudela FE uses both
  const rootAttrs = attrsOf(root);
  const timestamps = root.columns
    .filter((c) => (c.createDateColumn || c.updateDateColumn) && !rootAttrs.some(([k]) => k === c.name))
    .map((c) => [c.name, { property: c.name, type: 'date' }]);

  const text = `${BANNER}
// What ${resource.name} lists can be filtered and sorted on (TMF630 attribute style + JSONPath
// \`filter=\`): the resource's own attributes, its single references and its embedded lists.
import type { FilterSchema } from '../common/filter/filter.types';
${classes.map((cn) => `import { ${cn} } from '${importPathFor(cn)}';`).join('\n')}

export const ${constName}: FilterSchema = {
  entity: ${classOf(root)},
  attrs: ${renderAttrs(rootAttrs, 2)},
  refs: ${renderRefs(root, entityOf, 2)},
  arrays: ${arrays.length ? `{\n${arrays.join('\n')}\n  }` : '{}'},
  timestamps: ${renderAttrs(timestamps, 2)},
  reserved: [${parentParams.map(q).join(', ')}],
};
`;
  return { fileName: `${kebab(resource.name)}.filter.ts`, constName, text };
}
