import { pascal, kebab } from '../ir/naming.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';

/**
 * DTOs mirror the API payload, entities mirror the database. That separation is
 * why normalising single refs into their own tables (entityPlan.mjs) does not
 * change the DTOs at all: the wire format still carries a nested object.
 *
 * Create/update field sets come from the spec's own variant schemas - `_FVO`/`_MVO`
 * on v5, `_Create`/`_Update` on v4 - so optionality is the spec's, not inferred.
 * Types are taken from the resource's classification, since the variant schemas
 * mirror the resource shape (v5's Foo_FVO composes the same properties as Foo).
 */

/** Property names that must be quoted and are plain strings on the wire. */
const AT_PROPS = new Set(['@type', '@baseType', '@schemaLocation', '@referredType']);

function propKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`;
}

/** Validator stack per field kind, following the reference exactly. */
function decoratorsFor(field, required) {
  const api = required ? '@ApiProperty()' : '@ApiPropertyOptional()';
  const opt = required ? '@IsDefined()' : '@IsOptional()';

  if (field.kind === 'json') {
    // free-form passthrough: the reference validates nothing here
    return [required ? '@ApiProperty()' : '@ApiPropertyOptional()', opt];
  }
  if (field.tsType === 'Date' || /date/i.test(field.name)) {
    // dates arrive as ISO strings; the reference attaches no date validator
    return [api];
  }
  if (field.tsType === 'number') return [api];
  if (field.tsType === 'boolean') return [api, opt, '@IsBoolean()'];
  return [api, opt, '@IsString()'];
}

function wireType(field) {
  if (field.kind === 'json') return field.tsType.includes('[]') ? 'any[]' : 'any';
  if (field.tsType === 'Date') return 'string';
  return field.tsType;
}

/**
 * Nested DTO class registry: keeps names unique and emits each class once,
 * declared above the exported DTO in the same file (reference convention).
 */
function createRegistry() {
  const used = new Set();
  const classes = [];
  return {
    nameFor(parentClass, fieldName) {
      const preferred = `${pascal(fieldName)}Dto`;
      if (!used.has(preferred)) { used.add(preferred); return preferred; }
      const scoped = `${pascal(parentClass)}${pascal(fieldName)}Dto`;
      used.add(scoped);
      return scoped;
    },
    add(text) { classes.push(text); },
    all() { return classes; },
  };
}

function renderMember(name, field, required, typeOverride) {
  const lines = [];
  if (field?.description) lines.push(`  /** ${field.description.replace(/\s+/g, ' ').trim()} */`);
  if (typeOverride?.array) {
    lines.push(`  @ApiPropertyOptional({ type: [${typeOverride.dto}] })`);
    lines.push('  @IsOptional()');
    lines.push('  @IsArray()');
    // the spec's minItems is a real constraint; combined with @IsOptional it only
    // applies when the caller actually sends the array
    if (typeOverride.minItems) lines.push(`  @ArrayMinSize(${typeOverride.minItems})`);
    lines.push('  @ValidateNested({ each: true })');
    lines.push(`  @Type(() => ${typeOverride.dto})`);
    lines.push(`  ${propKey(name)}?: ${typeOverride.dto}[];`);
    return lines.join('\n');
  }
  if (typeOverride?.dto) {
    lines.push(required ? '  @ApiProperty()' : '  @ApiPropertyOptional()');
    lines.push(required ? '  @IsDefined()' : '  @IsOptional()');
    lines.push('  @ValidateNested()');
    lines.push(`  @Type(() => ${typeOverride.dto})`);
    lines.push(`  ${propKey(name)}${required ? '' : '?'}: ${typeOverride.dto};`);
    return lines.join('\n');
  }
  for (const d of decoratorsFor(field, required)) lines.push(`  ${d}`);
  lines.push(`  ${propKey(name)}${required ? '' : '?'}: ${wireType(field)};`);
  return lines.join('\n');
}

/** Build a nested DTO class for a sub-resource or a single ref. */
function nestedClass(registry, ownerClass, fieldName, spec, requiredNames = []) {
  const dtoName = registry.nameFor(ownerClass, fieldName);
  const members = [];

  // refs and sub-resources both expose id/href plus their own scalars
  if (spec.exposeIdHref) {
    members.push(renderMember('id', { tsType: 'string', kind: 'scalar' }, false));
    members.push(renderMember('href', { tsType: 'string', kind: 'scalar' }, false));
  }
  for (const f of spec.fields ?? []) {
    // sourceProp is the WIRE name: a reference wrapper stores the referred id in
    // `refId`, but the payload calls it `id`.
    const wireName = f.sourceProp ?? f.name;
    members.push(renderMember(wireName, f, requiredNames.includes(wireName)));
  }
  for (const fr of spec.flattenedRefs ?? []) {
    const inner = nestedClass(registry, dtoName, fr.name, {
      exposeIdHref: false,
      fields: fr.columns.map(c => ({
        name: c.sourceProp,
        tsType: c.tsType === 'Date' ? 'string' : c.tsType,
        kind: 'scalar',
      })),
    });
    members.push(renderMember(fr.name, { kind: 'scalar', tsType: 'any' }, false, { dto: inner }));
  }
  for (const child of spec.children ?? []) {
    const inner = nestedClass(registry, dtoName, child.propertyName, {
      exposeIdHref: !child.refLike,
      fields: child.fields,
      flattenedRefs: child.flattenedRefs,
      children: child.children,
    });
    members.push(renderMember(child.propertyName, { kind: 'scalar', tsType: 'any' }, false, { dto: inner, array: true }));
  }
  for (const at of ['@type', '@baseType', '@schemaLocation', '@referredType']) {
    if (spec.atProps?.includes(at)) {
      members.push(renderMember(at, { tsType: 'string', kind: 'scalar' }, false));
    }
  }

  registry.add([`class ${dtoName} {`, members.join('\n\n'), '}'].join('\n'));
  return dtoName;
}

function collectImports(text) {
  const validators = ['IsDefined', 'IsOptional', 'IsString', 'IsArray', 'ArrayMinSize', 'IsBoolean', 'ValidateNested']
    .filter(v => text.includes(`@${v}(`));
  const swagger = ['ApiProperty', 'ApiPropertyOptional'].filter(v => text.includes(`@${v}(`));
  const transformer = text.includes('@Type(') ? ['Type'] : [];
  return { validators, swagger, transformer };
}

function assemble(className, members, registry, extendsClause = '') {
  const bodyParts = [
    ...registry.all(),
    [`export class ${className}${extendsClause} {`, members.join('\n\n'), '}'].join('\n'),
  ];
  const body = bodyParts.join('\n\n');
  const { validators, swagger, transformer } = collectImports(body);

  const imports = [];
  if (swagger.length) imports.push(`import { ${swagger.join(', ')} } from '@nestjs/swagger';`);
  if (validators.length) imports.push(`import { ${validators.join(', ')} } from 'class-validator';`);
  if (transformer.length) imports.push(`import { ${transformer.join(', ')} } from 'class-transformer';`);
  return { imports, body };
}

/**
 * @param resource IR resource
 * @param mode 'create' | 'update'
 */
export function renderPayloadDto(resource, mode) {
  const shape = mode === 'create' ? resource.createShape : resource.updateShape;
  const className = `${mode === 'create' ? 'Create' : 'Update'}${resource.name}Dto`;

  // Fall back to the resource schema when the spec has no variant (pre-FVO v4 specs).
  const allowed = shape ? new Set(shape.properties) : null;
  const requiredNames = mode === 'create' ? (shape?.required ?? resource.required ?? []) : [];
  const include = name => !allowed || allowed.has(name);

  const registry = createRegistry();
  const members = [];
  const notes = [];

  if (shape?.allowsClientId) {
    members.push(renderMember('id', { tsType: 'string', kind: 'scalar' }, false));
  }

  for (const f of resource.fields) {
    if (!include(f.name)) continue;
    members.push(renderMember(f.name, f, requiredNames.includes(f.name)));
  }

  for (const fr of resource.flattenedRefs) {
    if (!include(fr.name)) continue;
    const dto = nestedClass(registry, resource.name, fr.name, {
      exposeIdHref: false,
      fields: fr.columns.map(c => ({
        name: c.sourceProp,
        tsType: c.tsType === 'Date' ? 'string' : c.tsType,
        kind: 'scalar',
      })),
    });
    members.push(renderMember(fr.name, { kind: 'scalar', tsType: 'any' }, requiredNames.includes(fr.name), { dto }));
  }

  for (const rr of resource.resourceRefs) {
    if (!include(rr.name)) continue;
    const dto = nestedClass(registry, resource.name, rr.name, {
      exposeIdHref: false,
      fields: (rr.projectedProps ?? ['id', 'href', 'name']).map(p => ({
        name: p, tsType: 'string', kind: 'scalar',
      })),
    });
    members.push(renderMember(rr.name, { kind: 'scalar', tsType: 'any' }, requiredNames.includes(rr.name), { dto }));
  }

  for (const sub of resource.subResources) {
    if (!include(sub.propertyName)) continue;
    const dto = nestedClass(registry, resource.name, sub.propertyName, {
      // a reference wrapper already carries id/href/@referredType in its fields
      exposeIdHref: !sub.refLike,
      fields: sub.fields,
      flattenedRefs: sub.flattenedRefs,
      children: sub.children,
    });
    members.push(renderMember(sub.propertyName, { kind: 'scalar', tsType: 'any' }, false,
      { dto, array: true, minItems: mode === 'create' ? sub.minItems : null }));
    if (sub.minItems) notes.push(`${sub.propertyName} minItems: ${sub.minItems} (enforced on create)`);
  }

  // TMF polymorphism: @type is required by the spec on create for v5 resources
  for (const at of ['@type', '@baseType', '@schemaLocation']) {
    if (!include(at)) continue;
    members.push(renderMember(at, { tsType: 'string', kind: 'scalar' }, requiredNames.includes(at)));
  }

  const { imports, body } = assemble(className, members, registry);
  const header = [
    BANNER,
    `// payload shape from ${shape?.schemaName ?? `${resource.name} (no variant schema in spec)`}`,
    ...notes.map(n => `// note: ${n}`),
  ].join('\n');

  return {
    fileName: `${mode}-${kebab(resource.name)}.dto.ts`,
    className,
    text: [header, imports.join('\n'), '', body, ''].join('\n'),
  };
}

/**
 * Query DTO extends the shared QueryBaseDto (fields/offset/limit/name/
 * lifecycleStatus/q/sort) and adds `id`, exactly like the reference. Which of
 * those filters actually get applied is the service's decision (M4), driven by
 * `houseFilters` - so a resource without a lifecycleStatus column never builds a
 * query against one.
 */
export function renderQueryDto(resource) {
  const className = `Query${resource.name}Dto`;
  const applied = Object.entries(resource.houseFilters)
    .filter(([, v]) => v).map(([k]) => k).join(', ');

  return {
    fileName: `query-${kebab(resource.name)}.dto.ts`,
    className,
    text: [
      BANNER,
      `// filters applied by the service: ${applied || 'none'}`,
      "import { IsOptional, IsString } from 'class-validator';",
      "import { ApiPropertyOptional } from '@nestjs/swagger';",
      "import { QueryBaseDto } from '../../common/dto/query-base.dto';",
      '',
      `export class ${className} extends QueryBaseDto {`,
      '  @ApiPropertyOptional()',
      '  @IsOptional()',
      '  @IsString()',
      '  id?: string;',
      '}',
      '',
    ].join('\n'),
  };
}

export function renderDtoBarrel(resource) {
  return {
    fileName: 'index.ts',
    text: [
      BANNER,
      `export { Create${resource.name}Dto } from './create-${kebab(resource.name)}.dto';`,
      `export { Update${resource.name}Dto } from './update-${kebab(resource.name)}.dto';`,
      `export { Query${resource.name}Dto } from './query-${kebab(resource.name)}.dto';`,
      '',
    ].join('\n'),
  };
}
