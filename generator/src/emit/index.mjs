import fs from 'node:fs';
import path from 'node:path';
import { kebab } from '../ir/naming.mjs';
import { buildEntityPlan, resolveEntityNames, checkSqliteJoinLimit } from './entityPlan.mjs';
import { renderEntity, entityFileName } from './entity.mjs';
import { renderPayloadDto, renderQueryDto, renderDtoBarrel } from './dto.mjs';
import { renderService } from './service.mjs';
import { renderController, renderModule, renderHooks } from './controller.mjs';
import { renderSeedData } from './seed.mjs';
import { resolveModuleName } from './moduleNames.mjs';
import { scaffoldContext } from '../scaffold/newService.mjs';
import { readManifest, writeManifest, componentEntry, writeWiring } from './wiring.mjs';

const BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';

/**
 * Emit entities + DTOs for every resource, then regenerate the global entities.ts
 * barrel so TypeORM registers everything.
 *
 * Names are resolved across ALL resources at once, so two resources referencing the
 * same schema share one normalised table instead of duplicating it, and any table
 * name past PostgreSQL's 63-byte identifier limit fails the run.
 *
 * Module directory is kebab(moduleName), where moduleName is normally
 * resource.name - but a resource whose name collides with a reserved infra
 * dir (event/subscription/listener/common, see moduleNames.mjs) is remapped
 * to a Tmf-prefixed name so it never overwrites scaffold-owned files. This
 * only affects the module's own directory + Controller/Service/Module class
 * names, never resource.name (DTOs, entity class, @type) or
 * resource.pathSegment (the HTTP route). Nested resources are emitted flat
 * for now; the reference nests them, which matters for controller routes in
 * M4, not for entity registration.
 */
export function emitResources(ir, options) {
  const { backendDir, host = null, mode = 'own', dryRun = false, databaseType = 'sqlite' } = options;
  const written = [];
  const warnings = [];

  // ── pass 1: plan every resource, collect all entities ──
  const plans = [];
  for (const resource of ir.resources) {
    const plan = buildEntityPlan(resource, options);
    warnings.push(...plan.warnings);
    const moduleName = resolveModuleName(resource.name);
    plans.push({ resource, plan, dir: kebab(moduleName), moduleName });

    // SQLite refuses to compile a query joining more than 64 tables; harmless
    // under postgres, so only warn when that's the (default) target.
    if (databaseType === 'sqlite') {
      const tableCount = plan.entities.length + resource.resourceRefs.length;
      const w = checkSqliteJoinLimit(resource.name, tableCount);
      if (w) warnings.push(w);
    }
  }

  const allEntities = plans.flatMap(p => p.plan.entities);
  const { names, merged, errors, collisions } = resolveEntityNames(allEntities);
  warnings.push(...collisions);
  if (errors.length) {
    const err = new Error(`entity naming failed:\n  - ${errors.join('\n  - ')}`);
    err.errors = errors;
    throw err;
  }

  const resolve = key => names.get(key) ?? null;

  // A shared entity is written ONCE, under the module of the first resource that
  // needs it. Import paths must point at where the file actually lands, so the
  // directory is keyed by final class name (first writer wins) - not by the plan
  // currently being rendered, which is what produced broken relative imports.
  const dirByClass = new Map();
  for (const p of plans) {
    for (const e of p.plan.entities) {
      const self = resolve(e.key);
      if (self && !dirByClass.has(self.className)) dirByClass.set(self.className, p.dir);
    }
  }
  const importDirOf = key => {
    const self = resolve(key);
    return self ? dirByClass.get(self.className) ?? '' : '';
  };

  const writeFile = (rel, content) => {
    written.push(rel);
    if (dryRun) return;
    const abs = path.join(backendDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
  };

  // ── pass 2: render ──
  const resourceModules = [];
  const seeds = [];
  const preserved = [];
  const barrelEntries = [];
  const emittedClasses = new Set();
  const perResource = [];

  for (const { resource, plan, dir, moduleName } of plans) {
    const rows = [];
    for (const entity of plan.entities) {
      const self = resolve(entity.key);
      // a merged duplicate resolves to a class another resource already emitted
      if (emittedClasses.has(self.className)) {
        rows.push({ ...self, kind: entity.kind, columns: entity.columns.length, relations: entity.relations.length, reused: true, softDelete: entity.softDelete });
        continue;
      }
      emittedClasses.add(self.className);

      const rel = `src/${dir}/entities/${entityFileName(self.className)}`;
      writeFile(rel, renderEntity(entity, self, resolve, importDirOf, dir));
      barrelEntries.push({
        className: self.className,
        importPath: `${dir}/entities/${entityFileName(self.className).replace(/\.ts$/, '')}`,
      });
      rows.push({
        ...self, kind: entity.kind,
        columns: entity.columns.length, relations: entity.relations.length,
        softDelete: entity.softDelete, reused: false,
      });
    }

    // entity classes this module must register with TypeOrmModule.forFeature,
    // including any shared entity that physically lives in another module dir
    const entityClasses = [];
    const seenForFeature = new Set();
    for (const entity of plan.entities) {
      const self = resolve(entity.key);
      if (seenForFeature.has(self.className)) continue;
      seenForFeature.add(self.className);
      const homeDir = dirByClass.get(self.className);
      entityClasses.push({
        className: self.className,
        importFrom: homeDir === dir
          ? `./entities/${kebab(self.className)}.entity`
          : `../${homeDir}/entities/${kebab(self.className)}.entity`,
      });
    }

    const importByClass = new Map(entityClasses.map(c => [c.className, c.importFrom]));
    const siblings = new Map(ir.resources.map(r => [
      r.name,
      { constant: ir.meta.basePathConstant, segment: r.pathSegment },
    ]));
    const svc = renderService(resource, plan, {
      resolve,
      basePathConstant: ir.meta.basePathConstant,
      eventTypeEnum: ir.meta.eventTypeEnum,
      notificationEvents: resource.notificationEvents ?? [],
      importPathFor: cn => importByClass.get(cn) ?? `./entities/${kebab(cn)}.entity`,
      siblings,
      host,
      moduleName,
    });
    const ctrl = renderController(resource, { basePathConstant: ir.meta.basePathConstant, host, moduleName });
    const mod = renderModule(resource, entityClasses, { moduleName });
    writeFile(`src/${dir}/${svc.fileName}`, svc.text);
    writeFile(`src/${dir}/${ctrl.fileName}`, ctrl.text);
    writeFile(`src/${dir}/${mod.fileName}`, mod.text);

    // hooks: written ONCE if absent, never overwritten (see plan section 7)
    const hooks = renderHooks(resource, { moduleName });
    const hooksAbs = path.join(backendDir, `src/${dir}/${hooks.fileName}`);
    if (dryRun || !fs.existsSync(hooksAbs)) {
      writeFile(`src/${dir}/${hooks.fileName}`, hooks.text);
    } else {
      preserved.push(`src/${dir}/${hooks.fileName}`);
    }

    resourceModules.push({
      resource: resource.name,
      dir,
      pathSegment: resource.pathSegment,
      moduleClass: mod.className,
      moduleImportPath: `${dir}/${mod.fileName.replace(/\.ts$/, '')}`,
      className: mod.className,
      importPath: `${dir}/${mod.fileName.replace(/\.ts$/, '')}`,
    });

    // seed data from the spec's POST examples, when the spec has any
    const seed = renderSeedData(resource);
    if (seed) {
      writeFile(`src/${dir}/${seed.fileName}`, seed.text);
      seeds.push({
        resource: resource.name,
        dir,
        serviceClass: svc.className,
        seedConst: seed.constName,
        count: seed.count,
      });
    }

    const create = renderPayloadDto(resource, 'create');
    const update = renderPayloadDto(resource, 'update');
    const query = renderQueryDto(resource);
    const barrel = renderDtoBarrel(resource);
    writeFile(`src/${dir}/dto/${create.fileName}`, create.text);
    writeFile(`src/${dir}/dto/${update.fileName}`, update.text);
    writeFile(`src/${dir}/dto/${query.fileName}`, query.text);
    writeFile(`src/${dir}/dto/${barrel.fileName}`, barrel.text);

    perResource.push({
      resource: resource.name,
      dir,
      entities: rows,
      dtos: [create.className, update.className, query.className],
      service: svc.className,
      controller: ctrl.className,
      module: mod.className,
      routes: Object.entries(resource.operations).filter(([, v]) => v).map(([k]) => k),
      options: plan.options,
    });
  }

  // In inject mode the host owns app.module.ts / entities.ts / tmf.constants.ts, so
  // they are NEVER regenerated - the caller inserts into them surgically instead.
  if (mode === 'inject') {
    return {
      written: written.sort(),
      warnings,
      perResource,
      entityCount: barrelEntries.length,
      merged,
      preserved,
      injectEntities: barrelEntries,
      injectModules: resourceModules,
      seeds,
      eventMembers: ir.resources.flatMap(r => r.notificationEvents ?? []).length,
      listenerRoutes: ir.listeners.length,
    };
  }

  // ── manifest merge, then regenerate every shared file from the UNION ──
  // A service can host several TMF components. Regenerating wiring from a single
  // IR silently dropped the others: emitting TMF674 wiped TMF673 out of
  // app.module.ts and left its controllers referencing a base-path constant that
  // was never written. The manifest is what makes the wiring additive.
  const ctx = scaffoldContext(ir, { serviceName: null, port: null });
  const manifest = readManifest(backendDir);
  const entry = componentEntry(ir, manifest.components[ir.meta.tmfNumber]);
  entry.resources = resourceModules;
  entry.entities = barrelEntries;
  entry.events = ir.resources.flatMap(r => r.notificationEvents ?? []);
  entry.listeners = ir.listeners.map(l => ({ eventName: l.eventName }));
  entry.seeds = seeds;
  manifest.components[ir.meta.tmfNumber] = entry;
  writeManifest(backendDir, manifest);

  const wiringFiles = writeWiring(backendDir, manifest, { databaseName: ctx.databaseName });
  written.push(...wiringFiles);

  return {
    written: written.sort(),
    warnings,
    perResource,
    entityCount: barrelEntries.length,
    merged,
    preserved,
    eventMembers: entry.events.length,
    listenerRoutes: entry.listeners.length,
    componentCount: Object.keys(manifest.components).length,
    wiringFiles: wiringFiles.length,
    seeds,
  };
}
