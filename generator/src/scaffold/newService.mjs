const here = path.dirname(url.fileURLToPath(import.meta.url));
const templatesDir = path.resolve(here, '..', '..', 'templates');

const GENERATED_BANNER = '// GENERATED by tmfgen - DO NOT EDIT. Re-run the generator instead.';

/* ── template rendering ──────────────────────────────────────────────── */

function walk(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(abs, base));
    else out.push(path.relative(base, abs).split(path.sep).join('/'));
  }
  return out;
}

function render(text, tokens) {
  return text.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in tokens)) throw new Error(`template placeholder ${m} has no value`);
    return tokens[key];
  });
}

/* ── generated-fresh files (not harvested) ───────────────────────────── */

function tmfConstants(ctx) {
  return [
    `export const ${ctx.basePathConstant} = '${ctx.basePath}';`,
    `export const ${ctx.eventExchangeConstant} = '${ctx.eventExchange}';`,
    '',
  ].join('\n');
}

/**
 * Regenerated wholesale on every run (re-run policy is always-overwrite), so no
 * injection markers are needed here. Markers only matter for Mode B, where the
 * generator edits a service it did not create.
 */
function entitiesBarrel(resourceEntities = []) {
  const imports = resourceEntities.map(e => `import { ${e.className} } from './${e.importPath}';`);
  const infra = [
    "import { EventSubscription } from './subscription/entities/event-subscription.entity';",
    "import { EventLog } from './event/entities/event-log.entity';",
  ];
  const names = [...resourceEntities.map(e => e.className), 'EventSubscription', 'EventLog'];
  return [
    GENERATED_BANNER,
    ...imports,
    ...infra,
    '',
    'export const entities = [',
    ...names.map(n => `  ${n},`),
    '];',
    '',
  ].join('\n');
}

export function appModule(ctx, resourceModules = []) {
  const imports = resourceModules.map(m => `import { ${m.className} } from './${m.importPath}';`);
  const entries = resourceModules.map(m => `    ${m.className},`);
  return `${GENERATED_BANNER}
import { Module } from '@nestjs/common';
import { ConfigModule, ConfigService } from '@nestjs/config';
import { TypeOrmModule } from '@nestjs/typeorm';
import { EventEmitterModule } from '@nestjs/event-emitter';
import { entities } from './entities';
${imports.join('\n')}${imports.length ? '\n' : ''}import { EventModule } from './event/event.module';
import { SubscriptionModule } from './subscription/subscription.module';
import { ListenerModule } from './listener/listener.module';

@Module({
  imports: [
    ConfigModule.forRoot(),
    EventEmitterModule.forRoot(),
    TypeOrmModule.forRootAsync({
      imports: [ConfigModule],
      inject: [ConfigService],
      useFactory: (configService: ConfigService) => {
        const dbType = configService.get<string>('DATABASE_TYPE') || 'sqlite';
        if (dbType === 'postgres') {
          return {
            type: 'postgres',
            host: configService.get<string>('DATABASE_HOST') || 'localhost',
            port: configService.get<number>('DATABASE_PORT') || 5432,
            username:
              configService.get<string>('DATABASE_USERNAME') || 'postgres',
            password:
              configService.get<string>('DATABASE_PASSWORD') || 'postgres',
            database:
              configService.get<string>('DATABASE_NAME') || '${ctx.databaseName}',
            entities,
            synchronize:
              configService.get<string>('DATABASE_SYNCHRONIZE') === 'true',
            logging: configService.get<string>('DATABASE_LOGGING') === 'true',
          };
        }
        return {
          type: 'sqlite',
          database: configService.get<string>('DATABASE_PATH') || './dev.db',
          entities,
          synchronize:
            configService.get<string>('DATABASE_SYNCHRONIZE') !== 'false',
          logging: configService.get<string>('DATABASE_LOGGING') === 'true',
        };
      },
    }),
${entries.join('\n')}${entries.length ? '\n' : ''}    EventModule,
    SubscriptionModule,
    ListenerModule,
  ],
})
export class AppModule {}
`;
}

/** Members are added per resource in M5; an empty enum is valid TypeScript. */
export function eventTypes(ctx, members = []) {
  const body = members.length
    ? members.map(m => `  ${m.enumMember} = '${m.eventName}',`).join('\n')
    : '  // no resources generated yet - members are emitted per resource';
  return `${GENERATED_BANNER}
export enum ${ctx.eventTypeEnum} {
${body}
}
`;
}

/**
 * Listener endpoints are pure no-op stubs in the reference: they log and echo a
 * subscription. Routes are derived from the spec's /listener/* paths, not assumed.
 */
export function listenerController(ctx, routes = []) {
  const handlers = routes.map(r => `
  @Post('${r.eventName}')
  @HttpCode(HttpStatus.CREATED)
  async handle${pascal(r.eventName)}(@Body() body: any) {
    this.logger.log('Received ${r.eventName}');
    return this.findSubscription(body);
  }`).join('\n');

  return `${GENERATED_BANNER}
import {
  Controller,
  Post,
  Body,
  Logger,
  HttpCode,
  HttpStatus,
} from '@nestjs/common';
import { ApiTags } from '@nestjs/swagger';
import { Repository } from 'typeorm';
import { InjectRepository } from '@nestjs/typeorm';
import { ${ctx.basePathConstant} } from '../common/constants/tmf.constants';
import { EventSubscription } from '../subscription/entities/event-subscription.entity';

@ApiTags('listener')
@Controller(\`\${${ctx.basePathConstant}}/listener\`)
export class ListenerController {
  private readonly logger = new Logger(ListenerController.name);

  constructor(
    @InjectRepository(EventSubscription)
    private readonly subscriptionRepository: Repository<EventSubscription>,
  ) {}

  private async findSubscription(body: any): Promise<EventSubscription> {
    if (body?.subscriptionId) {
      const sub = await this.subscriptionRepository.findOne({
        where: { id: body.subscriptionId },
      });
      if (sub) return sub;
    }
    const [latest] = await this.subscriptionRepository.find({
      order: { createdDate: 'DESC' },
      take: 1,
    });
    return (
      latest ||
      ({
        id: 'unknown',
        callback: '',
        createdDate: new Date(),
      } as unknown as EventSubscription)
    );
  }
${handlers}
}
`;
}

