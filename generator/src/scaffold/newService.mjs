/**
 * The sqlite block, unchanged: zero-setup dev default.
 *
 * Which one ships uncommented has to agree with the column types emitted for the
 * entities (emit --db), otherwise the service advertises a database it cannot boot on.
 */
function databaseBlockSqlite(ctx) {
  return [
    '# sqlite (default, zero-setup dev) or postgres',
    'DATABASE_TYPE=sqlite',
    'DATABASE_PATH=./dev.db',
    'DATABASE_SYNCHRONIZE=true',
    'DATABASE_LOGGING=false',
    '',
    '# postgres - uncomment and set DATABASE_TYPE=postgres',
    '# DATABASE_HOST=localhost',
    '# DATABASE_PORT=5432',
    '# DATABASE_USERNAME=postgres',
    '# DATABASE_PASSWORD=',
    `# DATABASE_NAME=${ctx.databaseName}`,
  ].join('\n');
}

/** Emitted when scaffolded with --db postgres, so entity types and env agree. */
