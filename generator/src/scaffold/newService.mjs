/**
 * Build the naming/token context from the IR. Kept separate so M3+ emitters can
 * reuse exactly the same derivations.
 */
export function scaffoldContext(ir, { serviceName, port, dbType = 'sqlite' }) {
  const m = ir.meta;
  const apiSegment = m.basePath.split('/').filter(Boolean)[1] || '';
  return {
    tmfNumber: m.tmfNumber,
    serviceName: serviceName || m.serviceNameSuggestion,
    // package/health identity follows the reference: kebab of the api segment
    serviceSlug: kebab(apiSegment),
    databaseName: snake(apiSegment.replace(/Management$/, '')),
    basePath: m.basePath,
    basePathConstant: m.basePathConstant,
    eventExchange: m.eventExchange,
    eventExchangeConstant: m.eventExchangeConstant,
    eventTypeEnum: m.eventTypeEnum,
    apiTitle: m.specTitle,
    apiDescription: `TMF${m.tmfNumber} ${m.specTitle} API v${m.versionMajor}`,
    apiVersion: m.specVersion,
    versionMajor: m.versionMajor,
    port,
    // decides which DATABASE_* block .env.example ships uncommented; entity column
    // types are decided separately at emit time (see emit/entity.mjs)
    dbType,
  };
}

export function scaffoldService(ir, options) {
  const ctx = scaffoldContext(ir, options);
  const backendDir = path.join(options.targetRoot, ctx.serviceName, 'backend');

  const tokens = {
    BASE_PATH_CONST: ctx.basePathConstant,
    EVENT_EXCHANGE_CONST: ctx.eventExchangeConstant,
    API_TITLE: ctx.apiTitle,
    API_DESCRIPTION: ctx.apiDescription,
    API_VERSION: ctx.apiVersion,
    SERVICE_SLUG: ctx.serviceSlug,
    PORT: String(ctx.port),
    // v5+ conformance profiles require @type in every response, including under
    // ?fields=; the v4 kits assert the opposite. See tmf-resource.util.ts.
    INCLUDE_ATYPE: String(Number(ctx.versionMajor) >= 5),
  };

  const written = [];
  const writeFile = (rel, content) => {
    const abs = path.join(backendDir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
    written.push(rel);
  };

  // 1. harvested templates (verbatim + tokenised are both rendered; verbatim
  //    files simply contain no placeholders)
  // `fe-*` dirs are FE templates (read directly by fe/scaffoldApp.mjs), not BE
  // service templates; their `{{APP_NAME}}` placeholder is unknown to BE tokens,
  // so walking them here would throw. ponytail: BE template roots stay flat;
  // when FE templates grow sub-layouts, move them out of templates/ instead.
  const templateFiles = walk(templatesDir)
    .filter(f => f !== 'harvest-report.json')
    .filter(f => !f.split('/')[0].startsWith('fe-'));
  for (const rel of templateFiles) {
    const text = fs.readFileSync(path.join(templatesDir, rel), 'utf8');
    let out = render(text, tokens);
    if (rel === 'package.json') {
      // the seed runner is compiled alongside main, so it runs from dist
      const pkg = JSON.parse(out);
      pkg.scripts = { ...pkg.scripts, seed: 'node dist/seed' };
      out = `${JSON.stringify(pkg, null, 2)}\n`;
    }
    writeFile(rel, out);
  }

  // 2. generated-fresh files
  writeFile('.env.example', envExample(ctx));

  // 3. register this component and generate every shared file from the manifest.
  //    A service can host several components, so wiring is never derived from one
  //    IR alone - see emit/wiring.mjs.
  const manifest = readManifest(backendDir);
  manifest.components[ir.meta.tmfNumber] = componentEntry(ir, manifest.components[ir.meta.tmfNumber]);
  writeManifest(backendDir, manifest);
  written.push(...writeWiring(backendDir, manifest, { databaseName: ctx.databaseName }));

  // 4. service-root package.json (backend only; frontend is added in the FE phase)
  const rootPkg = path.join(options.targetRoot, ctx.serviceName, 'package.json');
  fs.writeFileSync(rootPkg, serviceRootPackageJson(ctx), 'utf8');

  return {
    ctx,
    backendDir,
    serviceDir: path.join(options.targetRoot, ctx.serviceName),
    written: written.sort(),
    templateCount: templateFiles.length,
  };
}
